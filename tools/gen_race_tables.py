#!/usr/bin/env python3
"""Generate source/game/race_tables.h: DistributedRaceGame.posHprArray (the lane positions).

The table is literal data in DistributedRaceGame.__init__; it is read with ast, never copied by hand.

    .venv/bin/python -I tools/gen_race_tables.py            # write the header
    .venv/bin/python -I tools/gen_race_tables.py --check    # fail if it is stale
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / 'ref' if (ROOT / 'ref/open-toontown/toontown').is_dir() else ROOT / 'ref/ref'
SOURCE = REF / 'open-toontown/toontown/minigame/DistributedRaceGame.py'
OUT = ROOT / 'source/game/race_tables.h'


def pos_hpr_array():
    tree = ast.parse(SOURCE.read_text())
    for node in ast.walk(tree):
        if (isinstance(node, ast.Assign) and len(node.targets) == 1 and
                isinstance(node.targets[0], ast.Attribute) and node.targets[0].attr == 'posHprArray'):
            return ast.literal_eval(node.value)
    raise SystemExit('posHprArray not found in %s' % SOURCE)


def render(lanes):
    places = len(lanes[0])
    if any(len(lane) != places for lane in lanes):
        raise SystemExit('lanes have different lengths')
    lines = ['// GENERATED by tools/gen_race_tables.py from DistributedRaceGame.posHprArray. Do not edit.',
             '#pragma once', '', 'namespace tt::racegame {', '',
             '// Per lane, per board place: x, y, z, h relative to the race board (DistributedRaceGame',
             '// positionInPlace / walkInPlace).',
             'constexpr int kNumLanes = %d;' % len(lanes),
             'constexpr int kNumPlaces = %d;' % places,
             'constexpr float kLanePosHpr[kNumLanes][kNumPlaces][4] = {']
    for lane in lanes:
        lines.append('    {')
        for x, y, z, h in lane:
            lines.append('        {%rf, %rf, %rf, %rf},' % (float(x), float(y), float(z), float(h)))
        lines.append('    },')
    lines += ['};', '', '} // namespace tt::racegame', '']
    return '\n'.join(lines)


def main():
    text = render(pos_hpr_array())
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit('%s is stale; run tools/gen_race_tables.py' % OUT)
        return
    OUT.write_text(text)
    print(OUT)


if __name__ == '__main__':
    main()
