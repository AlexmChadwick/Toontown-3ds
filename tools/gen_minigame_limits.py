#!/usr/bin/env python3
"""Generate scalar per-hood limits from pinned upstream AST, without importing its client."""
import ast
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
UP = ROOT / 'ref/ref/open-toontown/toontown'
NAMES = ('ToontownCentral', 'DonaldsDock', 'DaisyGardens', 'MinniesMelodyland', 'TheBrrrgh', 'DonaldsDreamland')
values = {}
for node in ast.parse((UP / 'toonbase/ToontownGlobals.py').read_text()).body:
    if isinstance(node, ast.Assign):
        for name in node.targets:
            if isinstance(name, ast.Name) and name.id in NAMES:
                values[name.id] = ast.literal_eval(node.value)
context = {'__builtins__': {}, 'ToontownGlobals': SimpleNamespace(**values)}
def literal(node):
    return eval(compile(ast.Expression(node), '<upstream-limits>', 'eval'), context)
photo = {name: {} for name in NAMES}
for node in ast.parse((UP / 'minigame/PhotoGameGlobals.py').read_text()).body:
    if not isinstance(node, ast.Assign) or not isinstance(node.targets[0], ast.Subscript):
        continue
    key = node.targets[0]
    if not isinstance(key.value, ast.Subscript) or not isinstance(key.value.slice, ast.Attribute):
        continue
    name = key.value.slice.attr
    field = ast.literal_eval(key.slice)
    if name in photo and field in ('FILMCOUNT', 'TIME'):
        photo[name][field] = literal(node.value)
for node in ast.parse((UP / 'minigame/ToonBlitzGlobals.py').read_text()).body:
    if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id == 'GameDuration':
        duration = literal(node.value)
lines = ['// Generated by tools/gen_minigame_limits.py; PhotoGameGlobals and ToonBlitzGlobals.',
         '#pragma once', 'namespace tt::game {',
         'struct MinigameLimits { unsigned hood; int film, photoSeconds, twoDSeconds; };',
         'inline constexpr MinigameLimits kMinigameLimits[] = {']
for name in NAMES:
    lines.append('    {%d, %d, %d, %d},' % (values[name], photo[name]['FILMCOUNT'], photo[name]['TIME'], duration[values[name]]))
lines += ['};', '} // namespace tt::game', '']
(ROOT / 'source/game/minigame_limits.h').write_text('\n'.join(lines))
