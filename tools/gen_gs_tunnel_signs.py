#!/usr/bin/env python3
"""Goofy Speedway race tunnel signs -> source/world/gs_tunnel_signs.h.

DistributedRacePad.setTunnelSignText writes the pad's track name, race type, deposit and
qualify time onto the tunnel sign node RaceGlobals.getTunnelSignName(genre, padId) in the
playground geometry (GasolineAlley_TT, placed by the 8000 DNA). This writes each sign node's
zone-space matrix (with its scale) and the RaceGlobals / TTLocalizer tables the text needs.
Run with the repo .venv:
    .venv/bin/python -I tools/gen_gs_tunnel_signs.py [open-toontown dir] [resources dir]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'source/world/gs_tunnel_signs.h'


def main():
    ott = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'ref/open-toontown'
    res = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / 'ref/resources'
    sys.path.insert(0, str(ott))
    sys.path.insert(0, str(ROOT / 'tools/pipeline'))
    from panda3d.core import loadPrcFileData
    loadPrcFileData('', 'window-type none\naudio-library-name null\n')
    from direct.showbase.ShowBase import ShowBase
    from toontown.racing import RaceGlobals as RG
    from toontown.toonbase import TTLocalizerEnglish as L
    import dna, assemble, street_catalog

    base = ShowBase()
    _, storages, src = street_catalog.paths(8000)
    store = dna.Storage(base.loader, str(res))
    for s in storages:
        store.load(str(res / s))
    zone, _ = assemble.assemble(dna.parse_file(res / src, []), store, seed=1)

    lines = ['// Generated by tools/gen_gs_tunnel_signs.py from GasolineAlley_TT (8000 DNA),',
             '// toontown/racing/RaceGlobals.py and TTLocalizerEnglish.py.',
             '#pragma once', '', '#include <cstdint>', '', 'namespace tt::world::gs_signs {', '',
             'struct Sign {',
             '    uint8_t genre, padId; // RaceGlobals.getTunnelSignName(genre, padId)',
             '    float m[3][4];        // sign node -> zone space (rows; column 3 = position)',
             '};', '']
    signs = []
    for genre in range(3):
        for pad in range(4):
            name = RG.getTunnelSignName(genre, pad)
            node = zone.find('**/' + name)
            if node.isEmpty():
                raise SystemExit(f'missing tunnel sign {name}')
            mat = node.getMat(zone)  # row vectors: point * mat
            rows = []
            for i in range(3):
                rows.append([mat.getCell(c, i) for c in range(3)] + [mat.getCell(3, i)])
            signs.append((genre, pad, name, rows))
    lines.append(f'constexpr int kSigns = {len(signs)};')
    lines.append('constexpr Sign kSign[kSigns] = {')
    for genre, pad, name, rows in signs:
        body = ', '.join('{' + ', '.join(f'{v:.6f}f' for v in r) + '}' for r in rows)
        lines.append(f'    {{{genre}, {pad}, {{{body}}}}}, // {name}')
    lines.append('};')
    lines.append('')
    lines.append('struct Track {')
    lines.append('    uint16_t id;')
    lines.append('    uint8_t genre;')
    lines.append('    const char* name;  // TTLocalizer.KartRace_TrackNames')
    lines.append('    uint16_t fee;      // TrackDict[id][3][0]: ToonBattle entry fee (Practice is free)')
    lines.append('    float qualify;     // TrackDict[id][1]: seconds')
    lines.append('};')
    tracks = sorted(RG.TrackDict)
    lines.append(f'constexpr int kTracks = {len(tracks)};')
    lines.append('constexpr Track kTrack[kTracks] = {')
    for t in tracks:
        lines.append(f'    {{{t}, {RG.getTrackGenre(t)}, "{L.KartRace_TrackNames[t]}", '
                     f'{RG.TrackDict[t][3][0]}, {RG.TrackDict[t][1]:.1f}f}},')
    lines.append('};')
    names = ', '.join(f'"{n}"' for n in L.KartRace_RaceNames)
    lines.append(f'constexpr const char* kRaceNames[{len(L.KartRace_RaceNames)}] = {{{names}}};')
    # KartRace_DepositPhrase / QualifyPhrase end in a newline; the value is the second line.
    for name, phrase in (('kDepositLabel', L.KartRace_DepositPhrase), ('kQualifyLabel', L.KartRace_QualifyPhrase)):
        if not phrase.endswith('\n') or '\n' in phrase[:-1]:
            raise SystemExit(f'unexpected {name} phrase {phrase!r}')
        lines.append(f'constexpr const char* {name} = "{phrase[:-1]}";')
    lines.append('')
    lines.append('} // namespace tt::world::gs_signs')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'{OUT}: {len(signs)} signs, {len(tracks)} tracks')


if __name__ == '__main__':
    main()
