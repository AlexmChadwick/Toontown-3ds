#!/usr/bin/env python3
"""DistributedRingGame.__generateRings' difficultyPatterns (ref/open-toontown) ->
source/game/ring_tables.h: per hood, the 16-group patterns of ring track difficulty
(0 static keypad, 1 simple moving, 2 complex moving) that randomNumGen.choice picks from.
    python3 -I tools/gen_ring_tables.py [ref/open-toontown]
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'source/game/ring_tables.h'
HOODS = {'ToontownCentral': 2000, 'DonaldsDock': 1000, 'DaisyGardens': 5000, 'MinniesMelodyland': 4000,
         'TheBrrrgh': 3000, 'DonaldsDreamland': 9000}


class Globals:
    pass


def main():
    upstream = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'ref/open-toontown'
    src = (upstream / 'toontown/minigame/DistributedRingGame.py').read_text()
    tree = ast.parse(src)
    node = next(n for n in ast.walk(tree) if isinstance(n, ast.Assign) and len(n.targets) == 1
                and isinstance(n.targets[0], ast.Name) and n.targets[0].id == 'difficultyPatterns')
    g = Globals()
    for name, zone in HOODS.items():
        setattr(g, name, zone)
    patterns = eval(compile(ast.Expression(node.value), 'difficultyPatterns', 'eval'), {'ToontownGlobals': g})
    hoods = sorted(patterns)
    most = max(len(p) for p in patterns.values())
    lines = ['// Generated by tools/gen_ring_tables.py from DistributedRingGame.__generateRings.',
             '#pragma once', '', '#include <cstdint>', '', 'namespace tt::game::ringgame {', '',
             f'constexpr int kPatternHoods = {len(hoods)};',
             'constexpr uint32_t kPatternHood[kPatternHoods] = {' + ', '.join(map(str, hoods)) + '};',
             'constexpr int kPatternCount[kPatternHoods] = {' + ', '.join(str(len(patterns[h])) for h in hoods) + '};',
             f'constexpr int kMaxPatterns = {most};',
             'constexpr uint8_t kPatterns[kPatternHoods][kMaxPatterns][16] = {']
    for h in hoods:
        rows = []
        for p in patterns[h] + [[0] * 16] * (most - len(patterns[h])):
            assert len(p) == 16 and all(v in (0, 1, 2) for v in p), (h, p)
            rows.append('{' + ', '.join(map(str, p)) + '}')
        lines.append('    {' + ', '.join(rows) + '},')
    lines += ['};', '', '} // namespace tt::game::ringgame', '']
    OUT.write_text('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
