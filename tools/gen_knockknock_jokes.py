#!/usr/bin/env python3
"""Generate source/game/knockknock_jokes.h and knockknock_jokes.cpp from upstream.

Usage:
    .venv/bin/python -I tools/gen_knockknock_jokes.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))

sys.path.insert(0, os.path.join(ROOT, 'ref', 'ref', 'open-toontown'))
try:
    from toontown.building.KnockKnockJokes import KnockKnockJokes, KnockKnockContestJokes
except ImportError:
    from toontown.toonbase.TTLocalizerEnglish import KnockKnockJokes, KnockKnockContestJokes


def escape_c_string(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def generate_header(h_path):
    n_reg = len(KnockKnockJokes)
    max_idx = n_reg - 1
    content = f"""// GENERATED by tools/gen_knockknock_jokes.py. Do not edit.
#pragma once

#include <cstdint>

namespace tt::game {{

struct KnockKnockJoke {{
    const char* setup;
    const char* punchline;
}};

constexpr int kNumRegularJokes = {n_reg};

// Look up a knock-knock joke by zone and propId (building block number).
// Follows upstream DistributedKnockKnockDoor.py: checks contest jokes for
// Silly Street (2100), Loopy Lane (2200), Punchline Place (2300), and Polar Place (3300),
// falling back to KnockKnockJokes[propId % kNumRegularJokes].
KnockKnockJoke getKnockKnockJoke(uint32_t zoneId, uint16_t propId);

// Access regular joke array directly (0..{max_idx})
const KnockKnockJoke& getRegularJoke(int index);

// Number of regular jokes
int getRegularJokeCount();

}} // namespace tt::game
"""

    os.makedirs(os.path.dirname(h_path), exist_ok=True)
    with open(h_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Generated {h_path}")


def generate_source(cpp_path):
    lines = []
    lines.append("// GENERATED by tools/gen_knockknock_jokes.py. Do not edit.")
    lines.append('#include "game/knockknock_jokes.h"')
    lines.append('')
    lines.append('#include <cstddef>')
    lines.append('')
    lines.append('namespace tt::game {')
    lines.append('')
    lines.append('namespace {')
    lines.append('')
    lines.append(f'const KnockKnockJoke kRegularJokes[{len(KnockKnockJokes)}] = {{')
    for setup, punch in KnockKnockJokes:
        lines.append(f'    {{"{escape_c_string(setup)}", "{escape_c_string(punch)}"}},')
    lines.append('};')
    lines.append('')

    # Contest jokes structs
    lines.append('struct ContestJokeEntry {')
    lines.append('    uint32_t branch;')
    lines.append('    uint16_t propId;')
    lines.append('    KnockKnockJoke joke;')
    lines.append('};')
    lines.append('')

    contest_entries = []
    for branch, joke_data in sorted(KnockKnockContestJokes.items()):
        if isinstance(joke_data, dict):
            for pid, (setup, punch) in sorted(joke_data.items()):
                contest_entries.append((branch, pid, setup, punch))
        elif isinstance(joke_data, (list, tuple)):
            pid = 44 if branch == 2100 else (1 if branch == 2300 else 0)
            contest_entries.append((branch, pid, joke_data[0], joke_data[1]))

    lines.append(f'const ContestJokeEntry kContestJokes[{len(contest_entries)}] = {{')
    for branch, pid, setup, punch in contest_entries:
        lines.append(f'    {{{branch}u, {pid}u, {{"{escape_c_string(setup)}", "{escape_c_string(punch)}"}}}},')
    lines.append('};')
    lines.append('')
    lines.append('} // namespace')
    lines.append('')
    lines.append('int getRegularJokeCount() {')
    lines.append(f'    return {len(KnockKnockJokes)};')
    lines.append('}')
    lines.append('')
    lines.append('const KnockKnockJoke& getRegularJoke(int index) {')
    lines.append(f'    if (index < 0 || index >= {len(KnockKnockJokes)}) index = 0;')
    lines.append('    return kRegularJokes[index];')
    lines.append('}')
    lines.append('')
    lines.append('KnockKnockJoke getKnockKnockJoke(uint32_t zoneId, uint16_t propId) {')
    lines.append('    const uint32_t branch = zoneId - (zoneId % 100);')
    lines.append(f'    for (size_t i = 0; i < sizeof(kContestJokes)/sizeof(kContestJokes[0]); ++i) {{')
    lines.append('        if (kContestJokes[i].branch == branch && kContestJokes[i].propId == propId) {')
    lines.append('            return kContestJokes[i].joke;')
    lines.append('        }')
    lines.append('    }')
    lines.append(f'    const int idx = static_cast<int>(propId % {len(KnockKnockJokes)}u);')
    lines.append('    return kRegularJokes[idx];')
    lines.append('}')
    lines.append('')
    lines.append('} // namespace tt::game')
    lines.append('')

    os.makedirs(os.path.dirname(cpp_path), exist_ok=True)
    with open(cpp_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f"Generated {cpp_path}")


def main():
    h_path = os.path.join(ROOT, 'source', 'game', 'knockknock_jokes.h')
    cpp_path = os.path.join(ROOT, 'source', 'game', 'knockknock_jokes.cpp')
    generate_header(h_path)
    generate_source(cpp_path)


if __name__ == '__main__':
    main()
