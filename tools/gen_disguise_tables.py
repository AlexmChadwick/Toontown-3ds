#!/usr/bin/env python3
"""Generate source/ui/disguise_tables.h from upstream CogDisguiseGlobals."""
import ast
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UP = ROOT / 'ref' / 'ref' / 'open-toontown' if (ROOT / 'ref' / 'ref' / 'open-toontown').is_dir() else ROOT / 'ref' / 'open-toontown'
OUT = ROOT / 'source' / 'ui' / 'disguise_tables.h'

def main():
    path = UP / 'toontown' / 'coghq' / 'CogDisguiseGlobals.py'
    tree = ast.parse(path.read_text())
    env = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ('PartsPerSuit', 'PartsPerSuitBitmasks', 'MeritsPerLevel'):
                expr = ast.Expression(body=node.value)
                ast.fix_missing_locations(expr)
                env[node.targets[0].id] = eval(compile(expr, '<CogDisguiseGlobals>', 'eval'), {'__builtins__': {}}, {})

    # Load suit head types and base levels from SuitBattleGlobals
    battle_path = UP / 'toontown' / 'battle' / 'SuitBattleGlobals.py'
    b_tree = ast.parse(battle_path.read_text())
    suit_attrs = {}
    class MockObj:
        def __getattr__(self, name): return name
    for node in b_tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id == 'SuitAttributes':
                expr = ast.Expression(body=node.value)
                ast.fix_missing_locations(expr)
                suit_attrs = eval(compile(expr, '<SuitBattleGlobals>', 'eval'), {'__builtins__': {}}, {'TTLocalizer': MockObj()})

    dna_path = UP / 'toontown' / 'suit' / 'SuitDNA.py'
    d_tree = ast.parse(dna_path.read_text())
    head_types = []
    for node in d_tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id == 'suitHeadTypes':
                expr = ast.Expression(body=node.value)
                ast.fix_missing_locations(expr)
                head_types = eval(compile(expr, '<SuitDNA>', 'eval'), {'__builtins__': {}}, {})

    base_levels = [suit_attrs[c]['level'] for c in head_types]

    lines = [
        "// GENERATED by tools/gen_disguise_tables.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace tt::ui {",
        "",
        "constexpr uint8_t kPartsPerSuit[4] = { 17, 14, 12, 10 };",
        "constexpr uint32_t kPartsBitmasks[4] = { 131071, 130175, 56447, 56411 };",
        "",
        "constexpr uint8_t kCogBaseLevel[32] = {",
    ]
    for i in range(0, 32, 8):
        lines.append("    " + ", ".join(str(lvl) for lvl in base_levels[i:i+8]) + ",")
    lines.append("};")
    lines.append("")

    # Flatten MeritsPerLevel into an array with offsets
    lines.append("// Merits needed per cog index (32 cogs) and level offset")
    all_merits = []
    offsets = []
    for row in env['MeritsPerLevel']:
        offsets.append((len(all_merits), len(row)))
        all_merits.extend(row)

    lines.append(f"constexpr uint16_t kAllMerits[{len(all_merits)}] = {{")
    for i in range(0, len(all_merits), 12):
        lines.append("    " + ", ".join(str(m) for m in all_merits[i:i+12]) + ",")
    lines.append("};")
    lines.append("")

    lines.append("struct MeritRange { uint16_t offset, count; };")
    lines.append("constexpr MeritRange kMeritRanges[32] = {")
    for off, cnt in offsets:
        lines.append(f"    {{ {off}, {cnt} }},")
    lines.append("};")
    lines.append("")

    lines.extend([
        "inline uint16_t getNeededMerits(int dept, int type, int level) {",
        "    if (dept < 0 || dept >= 4 || type < 0 || type >= 8) return 500;",
        "    const int cogIdx = dept * 8 + type;",
        "    const int baseLvl = kCogBaseLevel[cogIdx];",
        "    int offset = level - baseLvl;",
        "    const MeritRange& r = kMeritRanges[cogIdx];",
        "    if (offset < 0) offset = 0;",
        "    if (offset >= r.count) offset = r.count - 1;",
        "    return kAllMerits[r.offset + offset];",
        "}",
        "",
        "inline bool isReadyForPromotion(int dept, int type, int level, uint16_t merits) {",
        "    const uint16_t needed = getNeededMerits(dept, type, level);",
        "    return needed > 0 && merits >= needed;",
        "}",
        "",
        "} // namespace tt::ui",
    ])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT}")

if __name__ == '__main__':
    main()
