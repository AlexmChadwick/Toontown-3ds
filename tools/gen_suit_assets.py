#!/usr/bin/env python3
"""Generate source/world/suit_assets.h from the Cog bake's suit_manifest.json
(tools/pipeline/bake_suit.py; docs/design/cogs.md): per head code the body, species scale,
hand colour and nametag height the runtime needs to draw real Cogs.

    .venv/bin/python -I tools/gen_suit_assets.py sdmc-out/3ds/toontown3ds/data/suit/suit_manifest.json source/world
"""
import json
import os
import sys


def main():
    manifest, out = sys.argv[1], sys.argv[2]
    m = json.load(open(manifest))
    heads = m['heads']
    lines = ['// GENERATED by tools/gen_suit_assets.py from suit_manifest.json. Do not edit.',
             '#pragma once', '', 'namespace tt::world {', '',
             'struct SuitAsset {',
             '    const char* code; // SuitDNA head code',
             "    char body;        // 'a' 'b' 'c': suit<B>_full.ttm",
             '    float scale;      // Suit.py species scale (body and head)',
             '    float hand[4];    // SuitDNA hand colour (TTM tint slot 4)',
             '    float nametagZ;   // Suit.setHeight + 1',
             '};', '',
             f'constexpr int kNumSuitAssets = {len(heads)};',
             'constexpr SuitAsset kSuitAssets[kNumSuitAssets] = {']
    for code in sorted(heads):
        h = heads[code]
        hand = ', '.join('%.4ff' % c for c in h['hand_color'])
        lines.append('    {"%s", \'%s\', %.6ff, {%s}, %.3ff},' % (code, h['body'], h['scale'], hand, h['nametag_z']))
    lines += ['};', '', 'inline const SuitAsset* findSuitAsset(const char* code) {',
              '    for (const SuitAsset& a : kSuitAssets) {',
              '        const char* x = a.code;',
              '        const char* y = code;',
              '        while (*x && *x == *y) ++x, ++y;',
              '        if (*x == *y) return &a;',
              '    }',
              '    return nullptr;', '}', '', '} // namespace tt::world', '']
    open(os.path.join(out, 'suit_assets.h'), 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main()
