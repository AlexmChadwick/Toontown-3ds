#!/usr/bin/env python3
"""Generate source/world/toon_dna_tables.h from the upstream toon DNA tables.

    .venv/bin/python -I tools/gen_toon_tables.py            # writes the header
    .venv/bin/python -I tools/gen_toon_tables.py --check    # exit 1 if it is stale

Sources (never hand-copy these into C++):
  toontown/toon/ToonDNA.py    toonSpeciesTypes, toonHeadTypes, toonTorsoTypes, toonLegTypes,
                              allColorsList, ClothesColors, Shirts/Sleeves/BoyShorts/GirlBottoms
                              (sizes + skirt flags), defaultBoy/GirlColorList, the Make-A-Toon
                              tailor collection (ShirtStyles/BottomStyles of TailorCollections[1])
  otp/otpbase/OTPGlobals.py   toonBodyScales, legHeightDict, torsoHeightDict, headHeightDict
                              (read with ast: the module itself needs panda3d.otp)
"""
import argparse
import ast
import os
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
UPSTREAM = os.path.join(ROOT, 'ref', 'open-toontown')
OUT = os.path.join(ROOT, 'source', 'world', 'toon_dna_tables.h')
sys.path.insert(0, UPSTREAM)

from toontown.toon import ToonDNA as T  # noqa: E402

SPECIES_NAMES = {'d': 'dog', 'c': 'cat', 'h': 'horse', 'm': 'mouse', 'r': 'rabbit', 'f': 'duck',
                 'p': 'monkey', 'b': 'bear', 's': 'pig'}  # ToonDNA.getSpeciesName


def otp_globals(*names):
    tree = ast.parse(open(os.path.join(UPSTREAM, 'otp', 'otpbase', 'OTPGlobals.py')).read())
    found = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if getattr(t, 'id', None) in names:
                    found[t.id] = ast.literal_eval(node.value)
    missing = set(names) - set(found)
    assert not missing, missing
    return found


def f(x):
    # Shortest decimal that round-trips the float32 value (VBase4 components are float32).
    s = str(np.float32(x))
    return s + 'f' if ('.' in s or 'e' in s) else s + '.0f'


def rgba_rows(colors):
    return ',\n'.join('    {%s}' % ', '.join(f(c[i]) for i in range(4)) for c in colors)


def u8_list(xs, per=16):
    xs = list(xs)
    rows = [', '.join(str(x) for x in xs[i:i + per]) for i in range(0, len(xs), per)]
    return ',\n'.join('    ' + r for r in rows)


def strs(xs):
    return ', '.join(f'"{x}"' for x in xs)


def mat_shirts(collection):
    out = []
    for style in collection:
        top, sleeve, colors = T.ShirtStyles[style]
        out += [(top, sleeve, c[0], c[1]) for c in colors]
    return out


def mat_bottoms(collection):
    out = []
    for style in collection:
        bot, colors = T.BottomStyles[style]
        out += [(bot, c) for c in colors]
    return out


def generate():
    g = otp_globals('toonBodyScales', 'legHeightDict', 'torsoHeightDict', 'headHeightDict')
    species = T.toonSpeciesTypes
    assert species == list(SPECIES_NAMES)
    mat = T.TailorCollections[T.MAKE_A_TOON]
    boy_shirts, girl_shirts = mat_shirts(mat[T.BOY_SHIRTS]), mat_shirts(mat[T.GIRL_SHIRTS])
    boy_bottoms, girl_bottoms = mat_bottoms(mat[T.BOY_SHORTS]), mat_bottoms(mat[T.GIRL_BOTTOMS])
    head_start = [T.getHeadStartIndex(s) for s in species]
    head_count = [len(T.getHeadList(s)) for s in species]
    for s, start, n in zip(species, head_start, head_count):
        assert T.toonHeadTypes[start:start + n] == T.getHeadList(s), s
    lines = [
        '// GENERATED by tools/gen_toon_tables.py from ref/open-toontown (toontown/toon/ToonDNA.py,',
        '// otp/otpbase/OTPGlobals.py). Do not edit; re-run the script.',
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        'namespace tt::world::dna_tables {',
        '',
        f'constexpr unsigned kNumSpecies = {len(species)};',
        f'constexpr char kSpeciesLetters[] = "{"".join(species)}"; // toonSpeciesTypes',
        f'constexpr const char* kSpeciesNames[kNumSpecies] = {{{strs(SPECIES_NAMES[s] for s in species)}}};',
        f'constexpr float kBodyScale[kNumSpecies] = {{{", ".join(f(g["toonBodyScales"][SPECIES_NAMES[s]]) for s in species)}}};',
        '// Heads of species i are kHeadTypes[kSpeciesHeadStart[i] .. + kSpeciesHeadCount[i]).',
        f'constexpr uint8_t kSpeciesHeadStart[kNumSpecies] = {{{", ".join(map(str, head_start))}}};',
        f'constexpr uint8_t kSpeciesHeadCount[kNumSpecies] = {{{", ".join(map(str, head_count))}}};',
        '',
        f'constexpr unsigned kNumHeadTypes = {len(T.toonHeadTypes)};',
        f'constexpr const char* kHeadTypes[kNumHeadTypes] = {{{strs(T.toonHeadTypes)}}};',
        f'constexpr float kHeadHeight[kNumHeadTypes] = {{{", ".join(f(g["headHeightDict"][h]) for h in T.toonHeadTypes)}}};',
        f'constexpr unsigned kNumTorsoTypes = {len(T.toonTorsoTypes)};',
        f'constexpr const char* kTorsoTypes[kNumTorsoTypes] = {{{strs(T.toonTorsoTypes)}}};',
        f'constexpr float kTorsoHeight[kNumTorsoTypes] = {{{", ".join(f(g["torsoHeightDict"][t]) for t in T.toonTorsoTypes)}}};',
        f'constexpr unsigned kNumLegTypes = {len(T.toonLegTypes)};',
        f'constexpr const char* kLegTypes[kNumLegTypes] = {{{strs(T.toonLegTypes)}}};',
        f'constexpr float kLegHeight[kNumLegTypes] = {{{", ".join(f(g["legHeightDict"][l]) for l in T.toonLegTypes)}}};',
        '',
        '// Clothing texture tables: only sizes matter at runtime (textures live in clothes.ttx).',
        f'constexpr unsigned kNumShirts = {len(T.Shirts)};',
        f'constexpr unsigned kNumSleeves = {len(T.Sleeves)};',
        f'constexpr unsigned kNumBoyShorts = {len(T.BoyShorts)};',
        f'constexpr unsigned kNumGirlBottoms = {len(T.GirlBottoms)};',
        '// GirlBottoms[i][1] == SKIRT',
        'constexpr uint8_t kGirlBottomIsSkirt[kNumGirlBottoms] = {',
        u8_list(1 if b[1] == T.SKIRT else 0 for b in T.GirlBottoms),
        '};',
        '',
        f'constexpr unsigned kNumAllColors = {len(T.allColorsList)};',
        'constexpr float kAllColors[kNumAllColors][4] = {',
        rgba_rows(T.allColorsList),
        '};',
        f'constexpr unsigned kNumClothesColors = {len(T.ClothesColors)};',
        'constexpr float kClothesColors[kNumClothesColors][4] = {',
        rgba_rows(T.ClothesColors),
        '};',
        '',
        '// Make-A-Toon body colors (defaultBoyColorList / defaultGirlColorList).',
        f'constexpr unsigned kNumDefaultBoyColors = {len(T.defaultBoyColorList)};',
        f'constexpr uint8_t kDefaultBoyColors[kNumDefaultBoyColors] = {{{", ".join(map(str, T.defaultBoyColorList))}}};',
        f'constexpr unsigned kNumDefaultGirlColors = {len(T.defaultGirlColorList)};',
        f'constexpr uint8_t kDefaultGirlColors[kNumDefaultGirlColors] = {{{", ".join(map(str, T.defaultGirlColorList))}}};',
        '',
        '// Make-A-Toon clothes: every (style, color) of TailorCollections[MAKE_A_TOON].',
        'struct MatShirt { uint8_t topTex, sleeveTex, topTexColor, sleeveTexColor; };',
        'struct MatBottom { uint8_t botTex, botTexColor; };',
    ]
    for name, rows in (('BoyShirts', boy_shirts), ('GirlShirts', girl_shirts)):
        lines += [f'constexpr unsigned kNumMat{name} = {len(rows)};',
                  f'constexpr MatShirt kMat{name}[kNumMat{name}] = {{',
                  ',\n'.join('    {%d, %d, %d, %d}' % r for r in rows), '};']
    for name, rows in (('BoyBottoms', boy_bottoms), ('GirlBottoms', girl_bottoms)):
        lines += [f'constexpr unsigned kNumMat{name} = {len(rows)};',
                  f'constexpr MatBottom kMat{name}[kNumMat{name}] = {{',
                  ',\n'.join('    {%d, %d}' % r for r in rows), '};']
    lines += ['', '} // namespace tt::world::dna_tables', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--out', default=OUT)
    args = ap.parse_args()
    text = generate()
    if args.check:
        current = open(args.out).read() if os.path.exists(args.out) else ''
        if current != text:
            print(f'{args.out} is stale; run tools/gen_toon_tables.py')
            sys.exit(1)
        print('up to date')
        return
    with open(args.out, 'w') as fh:
        fh.write(text)
    print('wrote', args.out)


if __name__ == '__main__':
    main()
