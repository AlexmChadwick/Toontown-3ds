#!/usr/bin/env python3
"""Generate source/ui/gag_data.{h,cpp}: gag tracks, names, experience levels, carry
limits and damage from upstream Open Toontown.

    .venv/bin/python -I tools/gen_gag_tables.py ref/open-toontown source/ui

Sources (read with ast, never imported or vendored):
  - toontown/toonbase/ToontownBattleGlobals.py  Levels, CarryLimits, AvPropDamage, MaxSkill
  - toontown/toonbase/TTLocalizerEnglish.py     BattleGlobalTracks, BattleGlobalAvPropStrings
"""
import ast
import os
import sys


def assignments(path, names):
    tree = ast.parse(open(path, encoding='utf-8').read())
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in names:
                out[node.targets[0].id] = node.value
    return out


def literal(node, env):
    """literal_eval that resolves `Levels[i][j]` subscripts from env (AvPropDamage)."""
    if isinstance(node, ast.Subscript):
        return literal(node.value, env)[literal(node.slice, env)]
    if isinstance(node, ast.Name):
        return env[node.id]
    if isinstance(node, (ast.Tuple, ast.List)):
        return [literal(e, env) for e in node.elts]
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        return -literal(node.operand, env)
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub)):
        lhs, rhs = literal(node.left, env), literal(node.right, env)
        return lhs + rhs if isinstance(node.op, ast.Add) else lhs - rhs
    return ast.literal_eval(node)


def main():
    ref, out = sys.argv[1], sys.argv[2]
    bg = os.path.join(ref, 'toontown/toonbase/ToontownBattleGlobals.py')
    loc = os.path.join(ref, 'toontown/toonbase/TTLocalizerEnglish.py')
    a = assignments(bg, {'Levels', 'CarryLimits', 'AvPropDamage', 'MaxSkill', 'UberSkill', 'regMaxSkill'})
    env = {}
    for name in ('UberSkill', 'regMaxSkill', 'Levels'):
        env[name] = literal(a[name], env)
    env['MaxSkill'] = literal(a['MaxSkill'], env)
    carry = literal(a['CarryLimits'], env)
    damage = literal(a['AvPropDamage'], env)
    max_skill = literal(a['MaxSkill'], env)
    l = assignments(loc, {'BattleGlobalTracks', 'BattleGlobalAvPropStrings'})
    tracks = literal(l['BattleGlobalTracks'], env)
    props = literal(l['BattleGlobalAvPropStrings'], env)
    levels = env['Levels']
    assert len(tracks) == 7 and all(len(p) == 7 for p in props) and all(len(x) == 7 for x in levels)

    def cstr(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

    h = f'''// Generated by tools/gen_gag_tables.py from upstream ToontownBattleGlobals /
// TTLocalizerEnglish. Do not edit.
#pragma once

#include <cstdint>

namespace tt::gags {{

constexpr int kTracks = 7; // toon-up, trap, lure, sound, throw, squirt, drop
constexpr int kLevels = 7;
constexpr int kCarryRows = {len(carry[0])}; // CarryLimits[track][row]: row = levels unlocked - 1
constexpr int kMaxSkill = {max_skill};

extern const char* const kTrackNames[kTracks];
extern const char* const kGagNames[kTracks][kLevels];
// Experience needed to unlock each level (Levels[track][level]).
extern const uint16_t kLevelExp[kTracks][kLevels];
// Max count per gag level, given how many levels of the track are unlocked.
extern const uint8_t kCarry[kTracks][kCarryRows][kLevels];
// AvPropDamage[track][level] = (min, max) damage (or heal) at min/max skill.
extern const uint16_t kDamage[kTracks][kLevels][2];
// Experience interval used by getAvPropDamage for each gag.
extern const uint16_t kDamageExp[kTracks][kLevels][2];

// Stock getAvPropDamage without organic / prop bonuses.  Those bonuses are
// server-owned and are not currently exposed to the native client.
int damageAtExp(int track, int level, uint16_t exp);

// Number of levels of `track` unlocked by `exp` experience (0 if the track is locked).
inline int levelsUnlocked(int track, uint16_t exp) {{
    int n = 0;
    for (int l = 0; l < kLevels; l++)
        if (exp >= kLevelExp[track][l]) n = l + 1;
    return n;
}}

}} // namespace tt::gags
'''
    c = ['// Generated by tools/gen_gag_tables.py. Do not edit.', '#include "ui/gag_data.h"', '',
         'namespace tt::gags {', '']
    c.append('const char* const kTrackNames[kTracks] = {' + ', '.join(cstr(t) for t in tracks) + '};')
    c.append('const char* const kGagNames[kTracks][kLevels] = {')
    for p in props:
        c.append('    {' + ', '.join(cstr(x) for x in p) + '},')
    c.append('};')
    c.append('const uint16_t kLevelExp[kTracks][kLevels] = {')
    for x in levels:
        c.append('    {' + ', '.join(str(v) for v in x) + '},')
    c.append('};')
    c.append('const uint8_t kCarry[kTracks][kCarryRows][kLevels] = {')
    for t in carry:
        c.append('    {' + ', '.join('{' + ', '.join(str(v) for v in row) + '}' for row in t) + '},')
    c.append('};')
    c.append('const uint16_t kDamage[kTracks][kLevels][2] = {')
    for t in damage:
        c.append('    {' + ', '.join('{%d, %d}' % (lv[0][0], lv[0][1]) for lv in t) + '},')
    c.append('};')
    c.append('const uint16_t kDamageExp[kTracks][kLevels][2] = {')
    for t in damage:
        c.append('    {' + ', '.join('{%d, %d}' % (lv[1][0], lv[1][1]) for lv in t) + '},')
    c.append('};')
    c += ['', '''int damageAtExp(int track, int level, uint16_t exp) {
    const int minDamage = kDamage[track][level][0];
    const int maxDamage = kDamage[track][level][1];
    const int minExp = kDamageExp[track][level][0];
    const int maxExp = kDamageExp[track][level][1];
    const int boundedExp = exp < maxExp ? exp : maxExp;
    // Equivalent to floor((exp - minExp) / expPerHp) in stock, expressed
    // with integers so ARM11 and host builds cannot disagree at a boundary.
    int result = ((boundedExp - minExp) * (maxDamage - minDamage + 1)) /
                 (maxExp - minExp + 1) + minDamage;
    if (result <= 0) result = minDamage;
    return result;
}''']
    c += ['', '} // namespace tt::gags', '']
    open(os.path.join(out, 'gag_data.h'), 'w').write(h)
    open(os.path.join(out, 'gag_data.cpp'), 'w').write('\n'.join(c))


if __name__ == '__main__':
    main()
