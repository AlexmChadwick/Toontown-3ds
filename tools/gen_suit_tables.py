#!/usr/bin/env python3
"""Generate source/world/suit_tables.h from the upstream cog tables.

    .venv/bin/python -I tools/gen_suit_tables.py            # writes the header
    .venv/bin/python -I tools/gen_suit_tables.py --check    # exit 1 if it is stale

TT_UPSTREAM=<dir> overrides ref/open-toontown (extra checkouts do not populate submodules).

Sources (read with ast / regex: the modules themselves need Panda3D's otp/toontown libs):
  toontown/suit/SuitDNA.py            suitHeadTypes (index = dept * 8 + tier), suitA/B/CTypes,
                                      suitDepts
  toontown/battle/SuitBattleGlobals.py SuitAttributes[name]: 'name', 'level', 'hp'
  toontown/toonbase/TTLocalizerEnglish.py  SuitFlunky ... (display names), Bossbot ... (depts)
  toontown/suit/Suit.py               generateSuit(): setHeight(...) per head code

SuitBase.setLevel: displayed level = SuitAttributes[name]['level'] + levelDist + 1
(getActualLevel) and maxHP = hp[levelDist]; the nametag text is
SuitBaseNameWithLevel = '%(name)s\\n%(dept)s\\nLevel %(level)s'.
"""
import argparse
import ast
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
UP = os.path.join(os.environ.get('TT_UPSTREAM', os.path.join(ROOT, 'ref', 'open-toontown')), 'toontown')
OUT = os.path.join(ROOT, 'source', 'world', 'suit_tables.h')


def parse(path):
    with open(os.path.join(UP, path), encoding='utf-8') as f:
        return ast.parse(f.read())


def top_assign(tree, name):
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if getattr(t, 'id', None) == name:
                    return node.value
    raise KeyError(name)


def build():
    dna = parse('suit/SuitDNA.py')
    heads = ast.literal_eval(top_assign(dna, 'suitHeadTypes'))
    bodies = {}
    for key, var in (('a', 'suitATypes'), ('b', 'suitBTypes'), ('c', 'suitCTypes')):
        for n in ast.literal_eval(top_assign(dna, var)):
            bodies[n] = key
    depts = ast.literal_eval(top_assign(dna, 'suitDepts'))

    loc = parse('toonbase/TTLocalizerEnglish.py')
    strings = {}
    for node in loc.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    strings[t.id] = node.value.value

    sbg = parse('battle/SuitBattleGlobals.py')
    attrs = {}
    for node in sbg.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', None) == 'SuitAttributes':
            for k, v in zip(node.value.keys, node.value.values):
                d = {}
                for kk, vv in zip(v.keys, v.values):
                    key = kk.value
                    if key == 'name':
                        d['name'] = strings[vv.attr].replace('\x03', '')
                    elif key == 'level':
                        d['level'] = vv.value
                    elif key == 'hp':
                        d['hp'] = [e.value for e in vv.elts]
                attrs[k.value] = d

    suit_py = open(os.path.join(UP, 'suit/Suit.py'), encoding='utf-8').read()
    heights = {}
    for m in re.finditer(r"dna\.name == '(\w+)':(.*?)(?=\n        elif dna\.name == |\n        else:|\n    def )", suit_py, re.S):
        h = re.search(r'self\.setHeight\(([\d.]+)\)', m.group(2))
        if h:
            heights[m.group(1)] = float(h.group(1))

    rows = []
    for i, code in enumerate(heads):
        a = attrs[code]
        assert len(a['hp']) == 5 and code in heights and code in bodies, code
        rows.append((code, a['name'], depts[i // 8], bodies[code], a['level'], a['hp'], heights[code]))
    dept_names = [strings[n] for n in ('Bossbot', 'Lawbot', 'Cashbot', 'Sellbot')]
    return rows, dept_names, depts


def emit():
    rows, dept_names, depts = build()
    o = ['// GENERATED by tools/gen_suit_tables.py from open-toontown (SuitDNA, SuitBattleGlobals,',
         '// TTLocalizerEnglish, Suit.py). Do not edit.',
         '#pragma once', '', 'namespace tt::world {', '',
         'struct SuitInfo {',
         '    const char* code;   // SuitDNA head code, as sent in setDNAString',
         '    const char* name;   // TTLocalizer display name',
         '    char dept;          // c l m s',
         '    char body;          // a b c (suit/SuitDNA.getSuitBodyType)',
         '    int baseLevel;      // SuitAttributes[name][\'level\']',
         '    int hp[5];          // SuitAttributes[name][\'hp\'] by levelDist',
         '    float height;       // Suit.generateSuit setHeight',
         '};', '',
         f'constexpr int kNumSuitTypes = {len(rows)};',
         'constexpr SuitInfo kSuitTypes[kNumSuitTypes] = {']
    for code, name, dept, body, level, hp, height in rows:
        o.append(f'    {{"{code}", "{name}", \'{dept}\', \'{body}\', {level}, {{{", ".join(map(str, hp))}}}, {height!r}f}},')
    o += ['};', '',
          '// Department names, index = position in SuitDNA.suitDepts "clms" (TTLocalizer.Bossbot, ...).',
          'constexpr const char* kSuitDeptNames[4] = {' + ', '.join(f'"{n}"' for n in dept_names) + '};',
          '', '} // namespace tt::world', '']
    return '\n'.join(o)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text = emit()
    if args.check:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('up to date' if same else 'STALE')
        return 0 if same else 1
    with open(OUT, 'w') as f:
        f.write(text)
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
