#!/usr/bin/env python3
"""Generate shared Toon IDs and per-part source timing from verified BAM headers."""
import os
import sys
from pathlib import Path
sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools/pipeline'))
from toon_anim_audit import sources,tables
import json


def main():
    reports = ROOT/'sdmc-out/animrt'
    reports.mkdir(parents=True,exist_ok=True)
    sources(ROOT/'ref/ref/resources',ROOT/'ref/ref/open-toontown',reports)
    t = tables()
    names = ['neutral','walk','run','jump-idle','wave']+[n for n in t['ANIMS'] if n not in ('neutral','walk','run','jump-idle','wave')]
    def enum(n):
        return 'kAnim'+('PushButton' if n=='pushbutton' else ''.join(p[0].upper()+p[1:] for p in n.split('-')))
    (ROOT/'source/world/toon_clips.inc').write_text('// GENERATED by tools/gen_toon_anims.py; stable IDs 0..4.\n'+''.join(f'TT_TOON_CLIP({enum(n)}, "{n}") // {i}\n' for i,n in enumerate(names)))
    records = json.loads((reports/'toon_sources.json').read_text())['sources']
    rows = {}
    for r in records:
        assert r['fps']==24
        rows.setdefault(r['kind']+'_'+r['code']+'_',[0]*len(names))[names.index(r['clip'])] = r['frames']
    (ROOT/'source/world/toon_timing.inc').write_text('// GENERATED source frame counts (24 fps), independent of LOD.\n'+''.join(
        '{"'+key+'", {'+','.join(map(str,value))+'}},\n' for key,value in sorted(rows.items())))


if __name__=='__main__':
    main()
