#!/usr/bin/env python3
"""Generate source/game/catch_tables.h from the upstream Catch minigame tables.

    .venv/bin/python -I tools/gen_catch_tables.py ref/open-toontown > source/game/catch_tables.h

Reads (with `ast`, nothing is imported or run):
  toontown/minigame/CatchGameGlobals.py   NumFruits (per player count and hood), the drop object types
  toontown/minigame/DropPlacer.py         RegionDropPlacer.DropRegionTables / Players2dropTable
"""
import ast
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else 'ref/open-toontown'
mg = os.path.join(root, 'toontown', 'minigame')


def parse(name):
    with open(os.path.join(mg, name)) as f:
        return ast.parse(f.read())


# ---- CatchGameGlobals ----
tree = parse('CatchGameGlobals.py')
num_fruits = None
for node in tree.body:
    if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', '') == 'NumFruits':
        num_fruits = ast.literal_eval(node.value)
assert num_fruits and len(num_fruits) == 4
HOODS = [2000, 1000, 5000, 4000, 3000, 9000]

# ---- DropPlacer ----
tree = parse('DropPlacer.py')
tables = None
players2 = None
for node in tree.body:
    if isinstance(node, ast.ClassDef) and node.name == 'RegionDropPlacer':
        for item in node.body:
            if isinstance(item, ast.Assign) and getattr(item.targets[0], 'id', '') == 'DropRegionTables':
                tables = ast.literal_eval(item.value)
            if isinstance(item, ast.Assign) and getattr(item.targets[0], 'id', '') == 'Players2dropTable':
                # [DropRegionTables[0], DropRegionTables[0], DropRegionTables[1], ...]
                players2 = [e.slice.value if isinstance(e.slice, ast.Constant) else e.slice.n
                            for e in item.value.elts]
assert tables and players2
rows = max(len(t) for t in tables)
cols = max(len(r) for t in tables for r in t)
regions = max(max(max(r) for r in t) for t in tables) + 1

print('// GENERATED by tools/gen_catch_tables.py from open-toontown toontown/minigame. Do not edit.')
print('// CatchGameGlobals.NumFruits and DropPlacer.RegionDropPlacer drop region tables.')
print('#pragma once')
print('#include <cstdint>')
print()
print('namespace tt::game::catchtab {')
print()
print('constexpr int kNumDropTables = %d;' % len(tables))
print('constexpr int kMaxTableDim = %d;' % max(rows, cols))
print('constexpr int kMaxRegions = %d;' % regions)
print('struct DropTable {')
print('    uint8_t rows, cols;')
print('    uint8_t region[%d][%d];' % (max(rows, cols), max(rows, cols)))
print('};')
print('// RegionDropPlacer.DropRegionTables[i]: region id per grid cell [row][col].')
print('constexpr DropTable kDropTables[kNumDropTables] = {')
for t in tables:
    d = max(rows, cols)
    print('    {%d, %d, {' % (len(t), len(t[0])))
    for r in t:
        print('        {%s},' % ', '.join(str(v) for v in r + [0] * (d - len(r))))
    for _ in range(d - len(t)):
        print('        {%s},' % ', '.join(['0'] * d))
    print('    }},')
print('};')
print('// Players2dropTable[numPlayers] -> index into kDropTables (clamped to the last entry).')
print('constexpr int kNumPlayers2Table = %d;' % len(players2))
print('constexpr uint8_t kPlayers2Table[kNumPlayers2Table] = {%s};' % ', '.join(str(i) for i in players2))
print()
print('// CatchGameGlobals.NumFruits[numPlayers - 1][hood]: what the AI scores a perfect game against.')
print('constexpr int kNumHoods = %d;' % len(HOODS))
print('constexpr uint32_t kHoods[kNumHoods] = {%s};' % ', '.join(str(h) for h in HOODS))
print('constexpr uint16_t kNumFruits[4][kNumHoods] = {')
for row in num_fruits:
    print('    {%s},' % ', '.join(str(row[h]) for h in HOODS))
print('};')
print()
print('} // namespace tt::game::catchtab')
