#!/usr/bin/env python3
"""MazeData / MazeGameGlobals / DistributedMazeGame (ref/open-toontown) -> source/game/maze_tables.h.

DistributedMazeGame.load picks MazeData.mazeNames[numPlayers - 1] (one maze per player count),
and __loadSuits takes 4 * numPlayers Flunkies whose cell walk periods come from the per-hood
slower / faster tables (the "Curve" tables when FASTER_SUIT_CURVE / SLOWER_SUIT_CURVE are set).
    python3 -I tools/gen_maze_tables.py [ref/open-toontown]
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'source/game/maze_tables.h'


def module_dict(path):
    out = {}
    exec(compile(path.read_text(), str(path), 'exec'), {}, out)
    return out


def suit_tables(path):
    """The self.<name> = {...} dict literals of DistributedMazeGame.__defineConstants."""
    tree = ast.parse(path.read_text())
    wanted = ('slowerSuitPeriods', 'slowerSuitPeriodsCurve', 'fasterSuitPeriods', 'fasterSuitPeriodsCurve')
    tables = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            t = node.targets[0]
            if isinstance(t, ast.Attribute) and t.attr in wanted and isinstance(node.value, ast.Dict):
                tables[t.attr] = ast.literal_eval(node.value)
    assert set(tables) == set(wanted), tables.keys()
    return [tables[w] for w in wanted]


def main():
    upstream = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'ref/open-toontown'
    mg = upstream / 'toontown/minigame'
    data = module_dict(mg / 'MazeData.py')
    lines = ['// Generated by tools/gen_maze_tables.py from toontown/minigame/MazeData.py,',
             '// MazeGameGlobals.py and DistributedMazeGame.__defineConstants.',
             '#pragma once', '', '#include <cstdint>', '', 'namespace tt::game::maze {', '']
    g = {}
    src = (mg / 'MazeGameGlobals.py').read_text()
    for name in ('SUIT_TIC_FREQ', 'WALK_SAME_DIRECTION_PROB', 'WALK_TURN_AROUND_PROB', 'GAME_DURATION'):
        for line in src.splitlines():
            if line.startswith(name + ' ='):
                g[name] = ast.literal_eval(line.split('=', 1)[1].strip().replace('int(', '(').replace('float(', '('))
    starts = ast.literal_eval(src.split('SUIT_START_POSITIONS =', 1)[1].strip())
    lines.append(f'constexpr float kCellWidth = {float(data["CELL_WIDTH"])}f; // MazeData.CELL_WIDTH')
    lines.append(f'constexpr int kSuitTicFreq = {g["SUIT_TIC_FREQ"]};')
    lines.append(f'constexpr int kWalkSameDirectionProb = {g["WALK_SAME_DIRECTION_PROB"]};')
    lines.append(f'constexpr int kWalkTurnAroundProb = {g["WALK_TURN_AROUND_PROB"]};')
    lines.append(f'constexpr float kGameDuration = {float(g["GAME_DURATION"])}f;')
    lines.append(f'constexpr int kMaxSuits = {len(starts)};')
    lines.append('constexpr float kSuitStartPositions[kMaxSuits][2] = {')
    lines += ['    {%rf, %rf},' % (float(a), float(b)) for a, b in starts]
    lines.append('};')
    lines.append('')
    names = [n[0] for n in data['mazeNames']]
    for i, name in enumerate(names):
        d = data['mazeData'][name]
        w, h = d['width'], d['height']
        table = d['collisionTable']
        assert len(table) == h and all(len(r) == w for r in table), name
        lines.append(f'// {name}')
        lines.append(f'constexpr uint8_t kCollision{i + 1}[{h}][{w}] = {{')
        lines += ['    {' + ','.join(str(int(c)) for c in row) + '},' for row in table]
        lines.append('};')
        lines.append(f'constexpr int8_t kTreasures{i + 1}[{len(d["treasurePosList"])}][2] = {{')
        lines += ['    {%d, %d},' % (int(p[0]), int(p[1])) for p in d['treasurePosList']]
        assert all(int(p[0]) == p[0] and int(p[1]) == p[1] for p in d['treasurePosList'])
        lines.append('};')
    lines.append('')
    lines.append('struct MazeInfo {')
    lines.append('    const char* model; // data/minigames/<model>.ttm')
    lines.append('    int width, height, originTX, originTY;')
    lines.append('    const uint8_t* collision; // [height][width], 1 = wall')
    lines.append('    const int8_t (*treasures)[2];')
    lines.append('    int numTreasures;')
    lines.append('};')
    lines.append('// MazeData.mazeNames[numPlayers - 1]')
    lines.append('constexpr MazeInfo kMazes[4] = {')
    for i, name in enumerate(names):
        d = data['mazeData'][name]
        lines.append(f'    {{"{name.rsplit("/", 1)[1]}", {d["width"]}, {d["height"]}, {d["originX"]}, {d["originY"]}, '
                     f'&kCollision{i + 1}[0][0], kTreasures{i + 1}, {len(d["treasurePosList"])}}},')
    lines.append('};')
    lines.append('')
    tables = suit_tables(mg / 'DistributedMazeGame.py')
    hoods = sorted(tables[0])
    counts = sorted(tables[0][hoods[0]])
    assert counts == [4, 8, 12, 16]
    lines.append(f'constexpr int kSuitHoods = {len(hoods)};')
    lines.append('constexpr uint32_t kSuitHood[kSuitHoods] = {' + ', '.join(map(str, hoods)) + '};')
    lines.append('// [table][hood][numSuits / 4 - 1][numSuits / 2]: slower, slowerCurve, faster, fasterCurve.')
    lines.append('constexpr uint8_t kSuitPeriods[4][kSuitHoods][4][8] = {')
    for t in tables:
        lines.append('    {')
        for hood in hoods:
            rows = []
            for n in counts:
                vals = t[hood][n]
                assert len(vals) == n // 2 and all(0 < v < 256 for v in vals)
                rows.append('{' + ', '.join(map(str, list(vals) + [0] * (8 - len(vals)))) + '}')
            lines.append('        {' + ', '.join(rows) + '},')
        lines.append('    },')
    lines.append('};')
    lines.append('')
    lines.append('} // namespace tt::game::maze')
    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
