#!/usr/bin/env python3
"""Generate source/ui/sos_tables.h from upstream NPCToons and TTLocalizer."""
import ast
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UP = ROOT / 'ref' / 'ref' / 'open-toontown' if (ROOT / 'ref' / 'ref' / 'open-toontown').is_dir() else ROOT / 'ref' / 'open-toontown'
OUT = ROOT / 'source' / 'ui' / 'sos_tables.h'

def main():
    npc_path = UP / 'toontown' / 'toon' / 'NPCToons.py'
    tree = ast.parse(npc_path.read_text())
    env = {
        'ToontownBattleGlobals': type('TBG', (), {
            'HEAL_TRACK': 0, 'TRAP_TRACK': 1, 'LURE_TRACK': 2, 'SOUND_TRACK': 3,
            'THROW_TRACK': 4, 'SQUIRT_TRACK': 5, 'DROP_TRACK': 6, 'NPC_RESTOCK_GAGS': 7,
            'NPC_TOONS_HIT': 8, 'NPC_COGS_MISS': 9
        })(),
        'ToontownGlobals': type('TG', (), {'MaxHpLimit': 137})()
    }
    friends = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ('HQnpcFriends', 'FOnpcFriends'):
                expr = ast.Expression(body=node.value)
                ast.fix_missing_locations(expr)
                val = eval(compile(expr, '<NPCToons>', 'eval'), {'__builtins__': {}}, env)
                friends.update(val)

    # Load localizer names
    loc_path = UP / 'toontown' / 'toonbase' / 'TTLocalizerEnglish.py'
    loc_tree = ast.parse(loc_path.read_text())
    names = {}
    loc_env = {
        'lToonHQ': 'Toon HQ',
        'lHQOfficerM': 'HQ Officer',
        'lHQOfficerF': 'HQ Officer',
        'Flippy': 'Flippy',
    }
    for node in loc_tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id == 'NPCToonNames':
                expr = ast.Expression(body=node.value)
                ast.fix_missing_locations(expr)
                names = eval(compile(expr, '<Localizer>', 'eval'), {'__builtins__': {}}, loc_env)

    # Generate source/ui/sos_tables.h
    lines = [
        "// GENERATED by tools/gen_sos_tables.py from open-toontown NPCToons.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace tt::ui {",
        "",
        "struct SosCardDef {",
        "    uint16_t npcId;",
        "    uint8_t track;      // 0..6 gag tracks, 7 restock, 8 toons hit, 9 cogs miss",
        "    int8_t level;       // gag level or restock track (-1 all)",
        "    uint16_t hp;        // heal/damage/value",
        "    uint8_t stars;      // upstream rarity 0..5; UI displays one to six pips",
        "    const char* name;",
        "};",
        "",
        f"constexpr int kNumSosCards = {len(friends)};",
        "constexpr SosCardDef kSosCards[kNumSosCards] = {",
    ]

    for npcId, (track, level, hp, stars) in sorted(friends.items()):
        name = names.get(npcId, f"NPC {npcId}").replace('"', '\\"')
        lines.append(f'    {{ {npcId}, {track}, {level}, {hp}, {stars}, "{name}" }},')

    lines.extend([
        "};",
        "",
        "inline const SosCardDef* findSosCard(uint16_t npcId) {",
        "    for (int i = 0; i < kNumSosCards; i++) {",
        "        if (kSosCards[i].npcId == npcId) return &kSosCards[i];",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "// Description string for SOS card type",
        "inline const char* sosTrackName(uint8_t track, int8_t level) {",
        "    switch (track) {",
        '    case 0: return "TOON-UP";',
        '    case 1: return "TRAP";',
        '    case 2: return "LURE";',
        '    case 3: return "SOUND";',
        '    case 4: return "THROW";',
        '    case 5: return "SQUIRT";',
        '    case 6: return "DROP";',
        "    case 7: {",
        "        switch (level) {",
        '        case 0: return "RESTOCK TOON-UP";',
        '        case 1: return "RESTOCK TRAP";',
        '        case 2: return "RESTOCK LURE";',
        '        case 3: return "RESTOCK SOUND";',
        '        case 4: return "RESTOCK THROW";',
        '        case 5: return "RESTOCK SQUIRT";',
        '        case 6: return "RESTOCK DROP";',
        '        default: return "RESTOCK ALL GAGS";',
        "        }",
        "    }",
        '    case 8: return "TOONS HIT";',
        '    case 9: return "COGS MISS";',
        '    default: return "SOS CARD";',
        "    }",
        "}",
        "",
        "} // namespace tt::ui",
    ])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT} ({len(friends)} SOS cards)")

if __name__ == '__main__':
    main()
