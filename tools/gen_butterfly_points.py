#!/usr/bin/env python3
"""ButterflyGlobals (ref/open-toontown) -> source/world/butterfly_points.h.

DistributedButterfly flies between ButterflyPoints[playground][area][index] (TTC and DG; the
estate is not played here). Run with the repo .venv (panda3d for Point3):
    .venv/bin/python -I tools/gen_butterfly_points.py
"""
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'ref/open-toontown/toontown/safezone/ButterflyGlobals.py'
OUT = ROOT / 'source/world/butterfly_points.h'


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    spec = importlib.util.spec_from_file_location('ButterflyGlobals', src)
    g = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(g)
    lines = ['// Generated by tools/gen_butterfly_points.py from toontown/safezone/ButterflyGlobals.py.',
             '#pragma once', '', 'namespace tt::world::butterfly {', '']
    lines.append('constexpr int kPlaygrounds = 2; // ButterflyGlobals.TTC, DG')
    lines.append(f'constexpr float kHeight[kPlaygrounds] = {{{g.BUTTERFLY_HEIGHT[0]}f, {g.BUTTERFLY_HEIGHT[1]}f}};')
    lines.append(f'constexpr float kTakeoff[kPlaygrounds] = {{{g.BUTTERFLY_TAKEOFF[0]}f, {g.BUTTERFLY_TAKEOFF[1]}f}};')
    lines.append(f'constexpr float kLanding[kPlaygrounds] = {{{g.BUTTERFLY_LANDING[0]}f, {g.BUTTERFLY_LANDING[1]}f}};')
    areas = [len(g.ButterflyPoints[p]) for p in (g.TTC, g.DG)]
    most = max(len(a) for p in (g.TTC, g.DG) for a in g.ButterflyPoints[p])
    lines.append(f'constexpr int kAreas[kPlaygrounds] = {{{areas[0]}, {areas[1]}}};')
    lines.append(f'constexpr int kMaxAreas = {max(areas)};')
    lines.append(f'constexpr int kMaxPoints = {most};')
    lines.append('// Points per area (unused entries are 0).')
    lines.append('constexpr int kNumPoints[kPlaygrounds][kMaxAreas] = {')
    for p in (g.TTC, g.DG):
        counts = [len(a) for a in g.ButterflyPoints[p]] + [0] * (max(areas) - len(g.ButterflyPoints[p]))
        lines.append('    {' + ', '.join(map(str, counts)) + '},')
    lines.append('};')
    lines.append('constexpr float kPoints[kPlaygrounds][kMaxAreas][kMaxPoints][3] = {')
    for p in (g.TTC, g.DG):
        lines.append('    {')
        for a in g.ButterflyPoints[p]:
            pts = ', '.join(f'{{{round(float(pt[0]), 4)!r}f, {round(float(pt[1]), 4)!r}f, {round(float(pt[2]), 4)!r}f}}' for pt in a)
            lines.append(f'        {{{pts}}},')
        lines.append('    },')
    lines.append('};')
    lines += ['', '} // namespace tt::world::butterfly', '']
    OUT.write_text('\n'.join(lines))
    print(OUT, areas, most)


if __name__ == '__main__':
    main()
