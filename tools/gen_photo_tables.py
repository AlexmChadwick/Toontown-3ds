#!/usr/bin/env python3
"""Generate source/game/photo_tables.h from PhotoGameGlobals.py.

    .venv/bin/python -I tools/gen_photo_tables.py [ref/open-toontown] > source/game/photo_tables.h

Never invent data or hand-copy numbers.
"""
import os
import sys

def main():
    root = sys.argv[1] if len(sys.argv) > 1 else 'ref/open-toontown'
    if not os.path.isdir(os.path.join(root, 'toontown')):
        root = 'ref/ref/open-toontown'

    src_path = os.path.join(root, 'toontown', 'minigame', 'PhotoGameGlobals.py')
    with open(src_path, 'r') as f:
        code = f.read()

    lines = []
    for line in code.splitlines():
        if line.startswith('from toontown') or line.startswith('from panda3d'):
            continue
        lines.append(line)

    filtered = '\n'.join(lines)
    class TG:
        ToontownCentral = 2000
        DonaldsDock = 1000
        DaisyGardens = 5000
        MinniesMelodyland = 4000
        TheBrrrgh = 3000
        DonaldsDreamland = 9000

    class Point3:
        def __init__(self, x, y, z): self.x, self.y, self.z = x, y, z

    scope = {'ToontownGlobals': TG, 'Point3': Point3}
    exec(filtered, scope)

    ad = scope['AREA_DATA']

    out = []
    out.append('// Generated by tools/gen_photo_tables.py from PhotoGameGlobals.py. Do not edit.')
    out.append('#pragma once')
    out.append('')
    out.append('#include <cstdint>')
    out.append('')
    out.append('namespace tt::photogame {')
    out.append('')

    out.append('constexpr int kNumStars = 5;')
    out.append('constexpr int kOnscreenAssignments = 5;')
    out.append(f'constexpr float kPhotoRotationMin = {scope["PHOTO_ROTATION_MIN"]:.2f}f;')
    out.append(f'constexpr float kPhotoRotationMax = {scope["PHOTO_ROTATION_MAX"]:.2f}f;')
    out.append(f'constexpr float kPhotoRotationVel = {scope["PHOTO_ROTATION_VEL"]:.2f}f;')
    out.append(f'constexpr float kPhotoAngleMin = {scope["PHOTO_ANGLE_MIN"]:.2f}f;')
    out.append(f'constexpr float kPhotoAngleMax = {scope["PHOTO_ANGLE_MAX"]:.2f}f;')
    out.append(f'constexpr float kPhotoAngleVel = {scope["PHOTO_ANGLE_VEL"]:.2f}f;')
    out.append('')

    out.append('struct PathPoint {')
    out.append('    float x, y, z;')
    out.append('};')
    out.append('')
    out.append('struct PoseOption {')
    out.append('    const char* name; // nullptr for none')
    out.append('    float weight;')
    out.append('    float interest;   // 1.0 for movement, 2.0 for emotes')
    out.append('};')
    out.append('')

    # Emit points for each hood and path
    hood_list = [2000, 1000, 5000, 4000, 3000, 9000]
    for hood in hood_list:
        data = ad[hood]
        paths = data['PATHS']
        for p_idx, path in enumerate(paths):
            out.append(f'constexpr PathPoint kHood_{hood}_Path_{p_idx}[{len(path)}] = {{')
            for pt in path:
                out.append(f'    {{ {pt.x:.3f}f, {pt.y:.3f}f, {pt.z:.3f}f }},')
            out.append('};')
        out.append('')

        # Anim options
        anims = data['ANIMATIONS']
        moves = data['MOVEMODES']
        rel = data['PATHANIMREL']
        for s_idx in range(len(anims)):
            combined = []
            for item in anims[s_idx]:
                name = f'"{item[0]}"' if item[0] else 'nullptr'
                combined.append((name, item[1], 2.0))
            for item in moves[s_idx]:
                name = f'"{item[0]}"' if item[0] else 'nullptr'
                combined.append((name, item[1], 1.0))
            out.append(f'constexpr PoseOption kHood_{hood}_Poses_{s_idx}[{len(combined)}] = {{')
            for c in combined:
                out.append(f'    {{ {c[0]}, {c[1]:.2f}f, {c[2]:.2f}f }},')
            out.append('};')
        out.append('')

    out.append('struct PathInfo {')
    out.append('    const PathPoint* points;')
    out.append('    int numPoints;')
    out.append('    int animSetIndex;')
    out.append('};')
    out.append('')
    out.append('struct PoseSetInfo {')
    out.append('    const PoseOption* poses;')
    out.append('    int numPoses;')
    out.append('};')
    out.append('')
    out.append('struct HoodPhotoData {')
    out.append('    uint32_t hoodId;')
    out.append('    int filmCount;')
    out.append('    int timeLimit;')
    out.append('    float camPosX, camPosY, camPosZ;')
    out.append('    float tripOffsetX, tripOffsetY, tripOffsetZ;')
    out.append('    float startH, startP, startR;')
    out.append('    const PathInfo* paths;')
    out.append('    int numPaths;')
    out.append('    const PoseSetInfo* poseSets;')
    out.append('    int numPoseSets;')
    out.append('};')
    out.append('')

    for hood in hood_list:
        data = ad[hood]
        paths = data['PATHS']
        anims = data['ANIMATIONS']
        rel = data['PATHANIMREL']
        out.append(f'constexpr PathInfo kHood_{hood}_PathInfo[{len(paths)}] = {{')
        for p_idx in range(len(paths)):
            out.append(f'    {{ kHood_{hood}_Path_{p_idx}, {len(paths[p_idx])}, {rel[p_idx]} }},')
        out.append('};')
        out.append(f'constexpr PoseSetInfo kHood_{hood}_PoseSetInfo[{len(anims)}] = {{')
        for s_idx in range(len(anims)):
            combined_len = len(anims[s_idx]) + len(data['MOVEMODES'][s_idx])
            out.append(f'    {{ kHood_{hood}_Poses_{s_idx}, {combined_len} }},')
        out.append('};')
        out.append('')

    out.append('inline const HoodPhotoData* getHoodPhotoData(uint32_t hoodId) {')
    for hood in hood_list:
        data = ad[hood]
        c = data['CAMERA_INTIAL_POSTION']
        tr = data['TRIPOD_OFFSET']
        hpr = data['START_HPR']
        out.append(f'    static const HoodPhotoData d_{hood} = {{')
        out.append(f'        {hood}, {data["FILMCOUNT"]}, {data["TIME"]},')
        out.append(f'        {c.x:.2f}f, {c.y:.2f}f, {c.z:.2f}f,')
        out.append(f'        {tr.x:.2f}f, {tr.y:.2f}f, {tr.z:.2f}f,')
        out.append(f'        {hpr.x:.4f}f, {hpr.y:.4f}f, {hpr.z:.4f}f,')
        out.append(f'        kHood_{hood}_PathInfo, {len(data["PATHS"])},')
        out.append(f'        kHood_{hood}_PoseSetInfo, {len(data["ANIMATIONS"])}')
        out.append('    };')
        out.append(f'    if (hoodId == {hood}) return &d_{hood};')
    out.append('    return &d_2000; // fallback TTC')
    out.append('}')
    out.append('')
    out.append('} // namespace tt::photogame')

    sys.stdout.write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
