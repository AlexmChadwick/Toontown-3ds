#!/usr/bin/env python3
"""Bake Donald's Dock boat (DistributedBoat) as its own model, deck collision and path tables.

    .venv/bin/python -I tools/pipeline/bake_boat.py [--out sdmc-out/3ds/toontown3ds/data/zones]
                                                    [--header source/world/boat_paths.h]

Upstream (docs/design/boat.md):
  toontown/safezone/DDSafeZoneLoader.py   boat = geom.find('**/donalds_boat'), wheel hidden
  toontown/safezone/DistributedBoat.py    Mopath phase_6/paths/dd-e-w and dd-w-e move the boat
The boat is a ModelNode inside phase_6/models/neighborhoods/donalds_dock.bam. It sits at the
origin of that model and the Mopaths move it; geometry is baked in boat-local coordinates.

Outputs
  <out>/1000_boat.ttm   boat geometry (static ttm, decals lifted like assemble.lift_decals)
  <out>/1000_boat.ttc   boat collision (deck floor, rails, camera walls) in boat-local coordinates
  <header>              kBoatEW / kBoatWE tables: Mopath sampled every kBoatPathStep seconds
                        as x, y, z, h (degrees); linear interpolation at runtime.
Deterministic: same inputs give identical files.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))

PATH_STEP = 0.1  # seconds between baked Mopath samples (hpr changes <= 9 deg/s)


def sample_paths(res):
    from direct.directutil import Mopath
    from panda3d.core import NodePath, PandaNode
    probe = NodePath(PandaNode('probe'))
    out = {}
    for key, stem in (('ew', 'dd-e-w'), ('we', 'dd-w-e')):
        mp = Mopath.Mopath()
        mp.loadFile(os.path.join(res, 'phase_6', 'paths', stem + '.bam'))
        duration = float(mp.getMaxT())
        n = int(duration / PATH_STEP) + 1
        pts = []
        for k in range(n + 1):
            t = min(k * PATH_STEP, duration)
            mp.goTo(probe, t)
            p, hpr = probe.getPos(), probe.getHpr()
            if abs(hpr[1]) > 1e-3 or abs(hpr[2]) > 1e-3:
                sys.exit(f'{stem}: pitch/roll in path ({tuple(hpr)}); the runtime only stores heading')
            pts.append((p[0], p[1], p[2], hpr[0]))
        out[key] = (duration, pts)
    return out


def write_header(path, paths):
    lines = ['// GENERATED by tools/pipeline/bake_boat.py -- do not edit.',
             '// Mopaths phase_6/paths/dd-e-w and dd-w-e sampled every kBoatPathStep seconds:',
             '// x, y, z, heading (degrees), in the Donald\'s Dock zone frame.',
             '#pragma once', '', 'namespace tt::world {', '',
             f'constexpr float kBoatPathStep = {PATH_STEP}f;']
    for key, label in (('ew', 'east -> west (SailingWest)'), ('we', 'west -> east (SailingEast)')):
        duration, pts = paths[key]
        lines += ['', f'// {label}', f'constexpr float kBoat{key.upper()}Duration = {duration:.4f}f;',
                  f'constexpr int kBoat{key.upper()}Count = {len(pts)};',
                  f'constexpr float kBoat{key.upper()}[{len(pts)}][4] = {{']
        for p in pts:
            lines.append('    {%.3ff, %.3ff, %.3ff, %.3ff},' % p)
        lines.append('};')
    lines += ['', '} // namespace tt::world', '']
    with open(path, 'w') as f:
        f.write('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--resources', default=os.path.join(ROOT, 'ref', 'resources'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'sdmc-out', '3ds', 'toontown3ds', 'data', 'zones'))
    ap.add_argument('--header', default=os.path.join(ROOT, 'source', 'world', 'boat_paths.h'))
    ap.add_argument('--max-tex', type=int, default=128)
    args = ap.parse_args()

    from panda3d.core import Filename, NodePath, PandaNode, loadPrcFileData
    loadPrcFileData('', 'window-type none\naudio-library-name null\nnotify-level warning\n'
                    'textures-power-2 none\nmodel-cache-dir')
    from direct.showbase.ShowBase import ShowBase
    import assemble
    import collide
    import extract
    import ttm

    base = ShowBase()
    bam = os.path.join(args.resources, 'phase_6', 'models', 'neighborhoods', 'donalds_dock.bam')
    model = base.loader.loadModel(Filename.fromOsSpecific(os.path.abspath(bam)))
    src = model.find('**/donalds_boat')
    if src.isEmpty():
        sys.exit('donalds_boat not found')
    # Detached copy so the boat's own transform (identity in the .bam) is the root frame.
    root = NodePath(PandaNode('boat_root'))
    boat = src.copyTo(root)
    wheel = boat.find('**/wheel')  # DDSafeZoneLoader.load hides the wheel (Donald's actor has one)
    if not wheel.isEmpty():
        wheel.hide()

    os.makedirs(args.out, exist_ok=True)
    mesh = collide.extract(boat, fallback_floor=False)  # before decal lifting; uses only CollisionNodes
    ttc = os.path.join(args.out, '1000_boat.ttc')
    cstats = mesh.write(ttc, cell_size=4.0, max_bytes=256 * 1024)

    assemble.lift_decals(boat)
    ex = extract.Extractor(max_tex=args.max_tex, layer_rules=assemble.LAYER_RULES)
    ex.add(boat)
    stats = ttm.write(os.path.join(args.out, '1000_boat.ttm'), ex.textures, ex.batches())
    paths = sample_paths(args.resources)
    write_header(args.header, paths)
    print(json.dumps({'ttm': stats, 'ttc': cstats,
                      'paths': {k: {'duration': v[0], 'samples': len(v[1]), 'start': v[1][0], 'end': v[1][-1]}
                                for k, v in paths.items()}}, indent=1, default=str))
    base.destroy()


if __name__ == '__main__':
    main()
