"""Generate racing constants from the pinned server and original kart locators. Run -I -B."""
import ast
import json
import runpy
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/clerks_test'))
from upstream import KartDNA
from panda3d.core import BamCache, NodePath, loadPrcFileData
loadPrcFileData('', 'window-type none\naudio-library-name null\nmodel-cache-dir\nnotify-level error')
from direct.showbase.ShowBase import ShowBase
base = ShowBase()
BamCache.getGlobalPtr().setActive(False)
racing = ROOT / 'ref/ref/open-toontown/toontown/racing'
values = runpy.run_path(str(racing / 'RaceGlobals.py'))
localizer = ast.parse((ROOT / 'ref/ref/open-toontown/toontown/toonbase/TTLocalizerEnglish.py').read_text())
strings = {}
for node in localizer.body:
    if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
        for target in node.targets:
            if isinstance(target, ast.Name):
                strings[target.id] = node.value.value
out = ['// Generated by tools/pipeline/gen_racing_tables.py; pinned upstream specification.', '#pragma once', 'namespace tt::racing {', 'constexpr unsigned char kGagFrequency[4][6] = ' + str(values['GagFreq']).replace('[','{').replace(']','}') + ';', 'constexpr const char* kRefusal[7] = {"", "",']
for key in ('NotEnoughTickets', 'NoBoard', 'NoKart', 'Occupied', 'TrackClosed'):
    out.append(json.dumps(strings['StartingBlock_' + key]) + ',')
out += ['};', 'struct KartAnchors { float seat[3]; float wheels[4][3]; };', 'constexpr KartAnchors kKartAnchors[3][3] = {']
for lod in range(3):
    out.append('{')
    for body in range(3):
        scene = NodePath('scene')
        root = scene.attachNewNode('kart')
        root.setScale(2)
        model = base.loader.loadModel(str(ROOT / 'ref/ref/resources' / (KartDNA.getKartModelPath(body,lod) + '.bam')))
        model.reparentTo(root)
        model.setH(180)
        model.setZ(.025)
        pitch = model.find('**/suspensionNode')
        seat = model.find('**/toonNode')
        seat.setScale(1 / pitch.getScale()[0] / 2)
        seat.setH((180 + pitch.getH()) % 360)
        seat.setPos(0, -1.3, -7)
        def vector(p):
            return '{' + ','.join(format(float(x), '.9g') + 'f' if '.' in format(float(x), '.9g') or 'e' in format(float(x), '.9g') else format(float(x), '.9g') + '.0f' for x in p) + '}'
        wheels = []
        for name in ('wheel*Node2','wheel*Node1','wheel*Node3','wheel*Node4'):
            center = model.find('**/' + name)
            wheel = center.getParent().attachNewNode('wheelbase')
            wheel.setPos(center.getPos())
            wheel.setZ(0)
            wheels.append(vector(wheel.getPos(scene)))
        out.append('{' + vector(seat.getPos(scene)) + ',{' + ','.join(wheels) + '}},')
        scene.removeNode()
    out.append('},')
out += ['};', '} // namespace tt::racing']
(ROOT / 'source/world/racing_tables.h').write_text('\n'.join(out) + '\n')
# SoundInterval timing comes from the original Vorbis sample count, without playing audio.
import struct
def duration(relative):
    data = (ROOT / 'ref/ref/resources' / relative).read_bytes()
    identification = data.index(b'\x01vorbis')
    rate = struct.unpack_from('<I', data, identification + 12)[0]
    offset = 0
    granule = 0
    while offset < len(data):
        assert data[offset:offset+4] == b'OggS'
        segments = data[offset+26]
        granule = max(granule, struct.unpack_from('<Q', data, offset+6)[0])
        offset += 27 + segments + sum(data[offset+27:offset+27+segments])
    return granule/rate
extra = '\nnamespace tt::racing {\nconstexpr float kKartStartSeconds[3] = {' + ','.join(format(duration('phase_6/audio/sfx/KART_Engine_start_%d.ogg' % body),'.9f') + 'f' for body in range(3)) + '};\n'
extra += 'constexpr float kKartAppearSeconds = %.9ff;\n}\n' % duration('phase_6/audio/sfx/KART_Appear.ogg')
with (ROOT / 'source/world/racing_tables.h').open('a') as output:
    output.write(extra)
