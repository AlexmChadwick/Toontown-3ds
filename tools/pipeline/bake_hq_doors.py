#!/usr/bin/env python3
"""Bake every Toon HQ's own swinging doors for the door movie (world/transition.cpp).

A Toon HQ model carries door_N (N = 0, 1): leftDoor_N, rightDoor_N and door_flat_N with the
doorFrameHoleLeft_N / doorFrameHoleRight_N decals. Closed, DistributedDoor shows the flat's
painted doors (the zone bake hides leaves and holes, assemble.py). Opening, it shows the side's
hole and turns that leaf about its own node to h = +-100 relative to door_origin_N. The zone
mesh keeps the flat, so the runtime draws the hole over it and the leaf on its hinge.

    romfs/baked/hq_doors/<hq>_<N>_{right,left,hole_right,hole_left}.ttm
        leaves: geometry relative to the leaf node (its hinge at the origin)
        holes:  geometry in door_origin_N space, 0.02 toward the outside (-y) to win depth
    source/world/hq_doors.h   per (hq, N): the hinges in door_origin_N space, whether a flat exists

    .venv/bin/python -I tools/pipeline/bake_hq_doors.py [--res ref/resources]
"""
import argparse
import os
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
ROOT = HERE.parents[1]

from panda3d.core import Filename, NodePath, TransformState, loadPrcFileData  # noqa: E402

loadPrcFileData('', 'window-type none\naudio-library-name null\nnotify-level warning\ntextures-power-2 none')
from direct.showbase.ShowBase import ShowBase  # noqa: E402

import extract  # noqa: E402
import ttm  # noqa: E402

# DNA landmark code suffix (toon_landmark_<key>) -> model (storage*.dna)
HQS = [
    ('hqTT', 'phase_3.5/models/modules/hqTT'),
    ('hqMM', 'phase_6/models/modules/hqMM'),
    ('hqBR', 'phase_8/models/modules/hqBR'),
    ('hqDG', 'phase_8/models/modules/hqDG'),
    ('hqDL', 'phase_8/models/modules/hqDL'),
    ('hqDD_SZ', 'phase_6/models/modules/tt_m_ara_dod_SZ_hq'),
    ('hqDD', 'phase_6/models/modules/tt_m_ara_dod_hq'),
]
OUT = ROOT / 'romfs' / 'baked' / 'hq_doors'
HEADER = ROOT / 'source' / 'world' / 'hq_doors.h'


def write(node, xform, out):
    holder = NodePath('part')
    c = node.copyTo(holder)
    c.setTransform(xform)
    c.show()
    for n in c.findAllMatches('**/;+h'):
        n.show()
    ex = extract.Extractor(max_tex=128)
    ex.add(holder)
    stats = ttm.write(str(out), ex.textures, ex.batches())
    holder.removeNode()
    return stats


def main():
    ap = argparse.ArgumentParser()
    default = ROOT / 'ref' / 'resources'
    if not (default / 'phase_3.5').is_dir():
        default = ROOT / 'ref' / 'ref' / 'resources'
    ap.add_argument('--res', type=Path, default=default)
    args = ap.parse_args()
    base = ShowBase()
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    total = 0
    for key, model in HQS:
        m = base.loader.loadModel(Filename.fromOsSpecific(str(args.res / (model + '.bam'))))
        for n in (0, 1):
            origin = m.find(f'**/door_origin_{n}')
            if origin.isEmpty():
                raise SystemExit(f'{model}: no door_origin_{n}')
            hinge = {}
            for side, leaf_name, hole_name in (('right', 'rightDoor', 'doorFrameHoleRight'),
                                               ('left', 'leftDoor', 'doorFrameHoleLeft')):
                leaf = m.find(f'**/{leaf_name}_{n}')
                hole = m.find(f'**/{hole_name}_{n}')
                if leaf.isEmpty() or hole.isEmpty():
                    raise SystemExit(f'{model}: door {n} is missing {leaf_name} / {hole_name}')
                p = leaf.getPos(origin)
                hinge[side] = (p[0], p[1], p[2])
                # The leaf's own rotation relative to door_origin is ~0; the movie sets it to (h, 0, 0).
                total += write(leaf, TransformState.makeIdentity(), OUT / f'{key}_{n}_{side}.ttm')['file_bytes']
                t = hole.getTransform(origin).setPos(hole.getPos(origin) + (0, -0.02, 0))
                total += write(hole, t, OUT / f'{key}_{n}_hole_{side}.ttm')['file_bytes']
            flat = not m.find(f'**/door_flat_{n}').isEmpty()
            rows.append((key, n, hinge['right'], hinge['left'], flat))
        m.removeNode()
    lines = ['// GENERATED by tools/pipeline/bake_hq_doors.py. Do not edit.', '#pragma once', '',
             'namespace tt::world {', '',
             '// A Toon HQ door: its leaves\' hinges in door_origin_N space and whether door_flat_N paints',
             '// the closed doors (without one the zone mesh keeps the closed leaves, so nothing swings).',
             'struct HqDoor {',
             '    const char* hq; // toon_landmark_<hq>, also romfs:/baked/hq_doors/<hq>_<n>_*.ttm',
             '    int n;',
             '    float right[3], left[3];',
             '    bool flat;',
             '};',
             f'constexpr HqDoor kHqDoors[{len(rows)}] = {{']
    for key, n, r, l, flat in rows:
        lines.append(f'    {{"{key}", {n}, {{{r[0]:.4f}f, {r[1]:.4f}f, {r[2]:.4f}f}}, '
                     f'{{{l[0]:.4f}f, {l[1]:.4f}f, {l[2]:.4f}f}}, {"true" if flat else "false"}}},')
    lines += ['};', '', '} // namespace tt::world', '']
    HEADER.write_text('\n'.join(lines))
    print(f'{len(rows) * 4} models, {total} bytes -> {OUT}; {HEADER}')


if __name__ == '__main__':
    main()
