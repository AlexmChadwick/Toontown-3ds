#!/usr/bin/env python3
"""Bake QuestPoster's art (toontown/quest/QuestPoster.py) into one atlas, plus the NPC head table.

The ToonTasks page and the Toon tab show each carried ToonTask as a QuestPoster: stickerbook_gui's
questCard (image_scale 0.8 x 0.58, tinted lightGreen once complete), a questPictureFrame tinted by
quest type, and an icon in the frame: the trolley, the package, cog_icons' cog and department
medallions, the Cog building, the friends box or Clarabelle. Each part is rendered offscreen into
its cell, aspect preserved and centred (ui_atlas.py).

Visit and "return to" posters show the NPC's head (createNpcToonHead). The runtime draws it with
the laff meter's species head in the NPC's head colour, so this also writes every NPCToonDict
entry's species and head colour: the DNA tuple, or newToonRandom(npcId, gender, 1) for 'r' NPCs,
as NPCToons.createLocalNPC builds them.

    romfs/baked/quest_poster.ttm      one 256x256 RGBA8 texture, a placeholder quad
    source/ui/quest_poster_atlas.h    the part rectangles (pixels, top-left origin)
    source/ui/quest_npc_heads.h       npcId -> species, head colour

    .venv/bin/python -I tools/pipeline/bake_quest_poster.py [--res ref/resources] [--png atlas.png]
"""
import argparse
import ast
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))

from panda3d.core import loadPrcFileData  # noqa: E402

loadPrcFileData('', 'window-type offscreen\nwin-size 512 512\naudio-library-name null\n'
                    'textures-power-2 none\nframebuffer-alpha 1')

import ui_atlas  # noqa: E402
from ui_atlas import Part  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'romfs' / 'baked' / 'quest_poster.ttm'
HEADER = ROOT / 'source' / 'ui' / 'quest_poster_atlas.h'
NPC_HEADER = ROOT / 'source' / 'ui' / 'quest_npc_heads.h'
ATLAS_W, ATLAS_H = 256, 256
BOOK = 'phase_3.5/models/gui/stickerbook_gui'
COGS = 'phase_3/models/gui/cog_icons'
PARTS = [
    Part('Card', BOOK, ['questCard'], (0, 0, 128, 128)),
    Part('Frame', BOOK, ['questPictureFrame'], (128, 0, 64, 64)),
    Part('Trolley', BOOK, ['trolley'], (192, 0, 64, 64)),
    Part('Package', BOOK, ['package'], (128, 64, 64, 64)),
    Part('Building', BOOK, ['COG_building'], (192, 64, 64, 64)),
    Part('Cog', COGS, ['cog'], (0, 128, 48, 48)),
    Part('CorpIcon', COGS, ['CorpIcon'], (48, 128, 48, 48)),
    Part('LegalIcon', COGS, ['LegalIcon'], (96, 128, 48, 48)),
    Part('MoneyIcon', COGS, ['MoneyIcon'], (144, 128, 48, 48)),
    Part('SalesIcon', COGS, ['SalesIcon'], (192, 128, 48, 48)),
    Part('Friends', 'phase_3.5/models/gui/friendslist_gui', ['FriendsBox_Closed'], (0, 176, 48, 48)),
    Part('Phone', BOOK, ['clarabelleCow'], (48, 176, 48, 48)),
]


def npc_heads(upstream):
    """[(npcId, species index, (r, g, b))] for every NPCToonDict entry."""
    sys.path.insert(0, str(upstream))
    from toontown.toon import ToonDNA
    src = ast.parse((upstream / 'toontown/toon/NPCToons.py').read_text())
    table = next(n.value for n in src.body if isinstance(n, ast.Assign)
                 and any(isinstance(t, ast.Name) and t.id == 'NPCToonDict' for t in n.targets))
    desc = {ast.literal_eval(k): v for k, v in zip(table.keys, table.values)}
    for n in ast.walk(src):
        if isinstance(n, ast.Assign) and isinstance(n.value, ast.Tuple):
            for t in n.targets:
                if isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name) and t.value.id == 'NPCToonDict':
                    desc[ast.literal_eval(t.slice)] = n.value
    rows = []
    for npc in sorted(desc):
        try:
            props = ast.literal_eval(desc[npc].elts[2])
            gender = ast.literal_eval(desc[npc].elts[3])
        except ValueError:
            continue  # computed entries (none in this revision)
        dna = ToonDNA.ToonDNA()
        if props == 'r':
            dna.newToonRandom(npc, gender, 1)
        else:
            dna.newToonFromProperties(*props)
        species = ToonDNA.toonSpeciesTypes.index(dna.head[0])
        rows.append((npc, species, tuple(ToonDNA.allColorsList[dna.headColor])[:3]))
    return rows


def write_npc_header(rows):
    lines = ['// GENERATED by tools/pipeline/bake_quest_poster.py. Do not edit.',
             '// QuestPoster.createNpcToonHead: every NPCToonDict entry\'s species (world::Species) and',
             '// head colour, from its DNA tuple or newToonRandom(npcId, gender, 1).',
             '#pragma once', '', '#include <cstdint>', '', 'namespace tt::ui {', '',
             'struct QuestNpcHead {', '    uint16_t npc;', '    uint8_t species, r, g, b;', '};',
             f'constexpr int kNumQuestNpcHeads = {len(rows)};',
             f'constexpr QuestNpcHead kQuestNpcHeads[kNumQuestNpcHeads] = {{ // sorted by npc']
    for npc, sp, (r, g, b) in rows:
        lines.append(f'    {{{npc}, {sp}, {round(r * 255)}, {round(g * 255)}, {round(b * 255)}}},')
    lines += ['};', '', '} // namespace tt::ui', '']
    NPC_HEADER.write_text('\n'.join(lines))
    print(NPC_HEADER, len(rows), 'NPCs')


def main():
    ap = argparse.ArgumentParser()
    default = ROOT / 'ref' / 'resources'
    if not (default / 'phase_4').is_dir():
        default = ROOT / 'ref' / 'ref' / 'resources'
    upstream = ROOT / 'ref' / 'open-toontown'
    if not (upstream / 'toontown').is_dir():
        upstream = ROOT / 'ref' / 'ref' / 'open-toontown'
    ap.add_argument('--res', type=Path, default=default)
    ap.add_argument('--upstream', type=Path, default=upstream)
    ap.add_argument('--png', type=Path, help='also write the atlas as a PNG (for review)')
    args = ap.parse_args()
    rows = ui_atlas.bake(args.res, PARTS, ATLAS_W, ATLAS_H, OUT, 'quest_poster', args.png)
    ui_atlas.write_header(HEADER, 'tools/pipeline/bake_quest_poster.py', 'tt::ui', 'kQuestPosterAtlasW',
                          'kQuestPosterAtlasH', ATLAS_W, ATLAS_H, 'QuestArt', 'QuestArtRect', rows,
                          'the part in the atlas (pixels, top-left origin)')
    write_npc_header(npc_heads(args.upstream))


if __name__ == '__main__':
    main()
