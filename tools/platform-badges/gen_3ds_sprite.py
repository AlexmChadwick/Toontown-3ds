#!/usr/bin/env python3
"""Platform badges for the 3DS: atlas_16.png -> source/ui/platform_badges_atlas.h.

    python3 -I tools/platform-badges/gen_3ds_sprite.py [atlas_16.png] > source/ui/platform_badges_atlas.h

Cells 1..8 of the 16 px atlas (cell index == platform enum id; cell 0 is empty) become one
128x16 GPU_RGBA4 texture, badge p at x = (p - 1) * 16. 4 KiB, uploaded once at init.
The data is pre-tiled (8x8 tiles, Morton order inside a tile, image top row first, as
tex3ds and tools/pipeline/ttm.py do), so the runtime only copies it into linear memory.
Straight alpha (citro2d blends SRC_ALPHA / ONE_MINUS_SRC_ALPHA). Deterministic.
"""
import os
import sys

from PIL import Image

CELL = 16
COUNT = 8
W, H = CELL * COUNT, CELL


def morton(x, y):
    i = 0
    for b in range(3):
        i |= ((x >> b) & 1) << (2 * b)
        i |= ((y >> b) & 1) << (2 * b + 1)
    return i


def q4(v):
    return (v * 15 + 127) // 255


def main(argv):
    src = argv[1] if len(argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'atlas_16.png')
    im = Image.open(src).convert('RGBA')
    if im.size != (CELL * (COUNT + 1), CELL):
        sys.exit(f'{src}: expected {(CELL * (COUNT + 1), CELL)}, got {im.size}')
    strip = im.crop((CELL, 0, CELL * (COUNT + 1), CELL))
    px = strip.load()
    out = [0] * (W * H)
    for y in range(H):
        for x in range(W):
            r, g, b, a = px[x, y]
            if q4(a) == 0:
                r = g = b = 0
            tile = (y // 8) * (W // 8) + (x // 8)
            out[tile * 64 + morton(x % 8, y % 8)] = q4(r) << 12 | q4(g) << 8 | q4(b) << 4 | q4(a)
    lines = ['// GENERATED by tools/platform-badges/gen_3ds_sprite.py from atlas_16.png. Do not edit.',
             '// Original hand-drawn badge art (tools/platform-badges/badges/*.svg).',
             '#pragma once', '', '#include <cstdint>', '', 'namespace tt::ui {', '',
             f'constexpr int kBadgeCell = {CELL};',
             f'constexpr int kBadgeTexW = {W};',
             f'constexpr int kBadgeTexH = {H};',
             f'constexpr int kBadgeCount = {COUNT}; // platforms 1..{COUNT}, badge p at x = (p - 1) * kBadgeCell',
             '// GPU_RGBA4, tiled (8x8 Morton tiles, top row first).',
             f'alignas(4) constexpr uint16_t kBadgeTexels[{W * H}] = {{']
    for i in range(0, len(out), 16):
        lines.append('    ' + ', '.join(f'0x{v:04x}' for v in out[i:i + 16]) + ',')
    lines += ['};', '', '} // namespace tt::ui', '']
    sys.stdout.write('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv)
