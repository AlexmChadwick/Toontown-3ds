#!/usr/bin/env python3
"""Generate source/game/name_tables.h and source/game/name_tables.cpp from
ref/ref/resources/phase_3/etc/NameMasterEnglish.txt.

This bakes the 435 Pick-a-Name words and categorized index lists into C++ tables
so the 3DS client can display the Name Shop tumblers, shuffle combinations, and
format pattern names offline without runtime disk access or Python.
"""

import os
import sys

def find_name_master():
    candidates = [
        "ref/ref/resources/phase_3/etc/NameMasterEnglish.txt",
        "ref/resources/phase_3/etc/NameMasterEnglish.txt",
        "../ref/resources/phase_3/etc/NameMasterEnglish.txt",
    ]
    for c in candidates:
        if os.path.isfile(c):
            return c
    raise FileNotFoundError("Could not find NameMasterEnglish.txt in candidates")

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(root)
    txt_path = find_name_master()

    entries = []
    with open(txt_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split("*")
            entry_id = int(parts[0])
            cat = int(parts[1])
            text = parts[2]
            entries.append((entry_id, cat, text))

    entries.sort(key=lambda x: x[0])
    total = len(entries)
    assert total == 435, f"Expected 435 entries, got {total}"
    for i, (eid, cat, text) in enumerate(entries):
        assert eid == i, f"Expected contiguous IDs, but entry {i} has id {eid}"

    # Build categorized lists
    male_titles = [i for i, (eid, cat, text) in enumerate(entries) if cat in (0, 2)]
    male_titles.sort(key=lambda i: entries[i][2].lower())

    female_titles = [i for i, (eid, cat, text) in enumerate(entries) if cat in (1, 2)]
    female_titles.sort(key=lambda i: entries[i][2].lower())

    male_firsts = [i for i, (eid, cat, text) in enumerate(entries) if cat in (3, 5)]
    male_firsts.sort(key=lambda i: entries[i][2].lower())

    female_firsts = [i for i, (eid, cat, text) in enumerate(entries) if cat in (4, 5)]
    female_firsts.sort(key=lambda i: entries[i][2].lower())

    last_prefixes = [i for i, (eid, cat, text) in enumerate(entries) if cat in (6, 7)]
    last_prefixes.sort(key=lambda i: entries[i][2].lower())

    last_suffixes = [i for i, (eid, cat, text) in enumerate(entries) if cat == 8]
    last_suffixes.sort(key=lambda i: entries[i][2].lower())

    header_content = """// GENERATED by tools/gen_name_tables.py. Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>

namespace tt::game {

// Name categories from NameMasterEnglish.txt:
// 0 - boyTitle, 1 - girlTitle, 2 - neutralTitle,
// 3 - boyFirst, 4 - girlFirst, 5 - neutralFirst,
// 6 - capPrefix, 7 - lastPrefix, 8 - lastSuffix
constexpr uint8_t kCatBoyTitle = 0;
constexpr uint8_t kCatGirlTitle = 1;
constexpr uint8_t kCatNeutralTitle = 2;
constexpr uint8_t kCatBoyFirst = 3;
constexpr uint8_t kCatGirlFirst = 4;
constexpr uint8_t kCatNeutralFirst = 5;
constexpr uint8_t kCatCapPrefix = 6;
constexpr uint8_t kCatLastPrefix = 7;
constexpr uint8_t kCatLastSuffix = 8;

constexpr int kTotalNameMasterEntries = 435;

struct NameMasterEntry {
    int16_t id;
    uint8_t category;
    const char* text;
};

// Returns pointer to table of all 435 entries (contiguous 0..434).
const NameMasterEntry* getAllNameEntries();
const char* getNameString(int16_t id);
uint8_t getNameCategory(int16_t id);

// True if id is a capitalized prefix ("Mc" or "Mac", category 6: id 242 or 243).
bool isCapPrefix(int16_t id);

// Gender-specific lists for Pick-a-Name columns:
int getTitleCount(bool male);
int16_t getTitleId(bool male, int index);

int getFirstCount(bool male);
int16_t getFirstId(bool male, int index);

int getPrefixCount();
int16_t getPrefixId(int index);

int getSuffixCount();
int16_t getSuffixId(int index);

// Find index within the respective list given an id (-1 if not found)
int findTitleIndex(bool male, int16_t id);
int findFirstIndex(bool male, int16_t id);
int findPrefixIndex(int16_t id);
int findSuffixIndex(int16_t id);

// Builds the full display / server name string from the 4-part pattern.
// p is -1 if that part is omitted.
// f is the capitalization flag (f1=0 for 'von', f3=1 if prefix is capPrefix).
void buildPatternName(int16_t p1, uint8_t f1,
                      int16_t p2, uint8_t f2,
                      int16_t p3, uint8_t f3,
                      int16_t p4, uint8_t f4,
                      char* out, size_t outSize);

// Generates a random pattern adhering to upstream NameGenerator.py rules.
// outP receives 4 ids (or -1 if omitted), outF receives 4 flags (0 or 1).
void randomPattern(bool male, int16_t outP[4], uint8_t outF[4]);

} // namespace tt::game
"""

    with open("source/game/name_tables.h", "w", encoding="utf-8") as f:
        f.write(header_content)

    cpp_lines = [
        "// GENERATED by tools/gen_name_tables.py. Do not edit.",
        '#include "game/name_tables.h"',
        "",
        "#include <cctype>",
        "#include <cstdlib>",
        "#include <cstring>",
        "",
        "namespace tt::game {",
        "",
        "namespace {",
        "",
        "const NameMasterEntry kNameMaster[435] = {",
    ]

    for eid, cat, text in entries:
        escaped = text.replace('\\', '\\\\').replace('"', '\\"')
        cpp_lines.append(f'    {{{eid}, {cat}, "{escaped}"}},')
    cpp_lines.append("};")
    cpp_lines.append("")

    def emit_array(name, arr):
        lines = [f"const int16_t {name}[{len(arr)}] = {{"]
        chunk = []
        for v in arr:
            chunk.append(str(v))
            if len(chunk) == 12:
                lines.append("    " + ", ".join(chunk) + ",")
                chunk = []
        if chunk:
            lines.append("    " + ", ".join(chunk) + ",")
        lines.append("};")
        return "\n".join(lines)

    cpp_lines.append(emit_array("kMaleTitles", male_titles))
    cpp_lines.append("")
    cpp_lines.append(emit_array("kFemaleTitles", female_titles))
    cpp_lines.append("")
    cpp_lines.append(emit_array("kMaleFirsts", male_firsts))
    cpp_lines.append("")
    cpp_lines.append(emit_array("kFemaleFirsts", female_firsts))
    cpp_lines.append("")
    cpp_lines.append(emit_array("kLastPrefixes", last_prefixes))
    cpp_lines.append("")
    cpp_lines.append(emit_array("kLastSuffixes", last_suffixes))
    cpp_lines.append("")
    cpp_lines.append("} // namespace")
    cpp_lines.append("")

    cpp_lines.append("""const NameMasterEntry* getAllNameEntries() {
    return kNameMaster;
}

const char* getNameString(int16_t id) {
    if (id >= 0 && id < kTotalNameMasterEntries) {
        return kNameMaster[id].text;
    }
    return "";
}

uint8_t getNameCategory(int16_t id) {
    if (id >= 0 && id < kTotalNameMasterEntries) {
        return kNameMaster[id].category;
    }
    return 0xFF;
}

bool isCapPrefix(int16_t id) {
    return id == 242 || id == 243;
}

int getTitleCount(bool male) {
    return male ? sizeof(kMaleTitles) / sizeof(kMaleTitles[0])
                : sizeof(kFemaleTitles) / sizeof(kFemaleTitles[0]);
}

int16_t getTitleId(bool male, int index) {
    const int count = getTitleCount(male);
    if (index < 0 || index >= count) return -1;
    return male ? kMaleTitles[index] : kFemaleTitles[index];
}

int getFirstCount(bool male) {
    return male ? sizeof(kMaleFirsts) / sizeof(kMaleFirsts[0])
                : sizeof(kFemaleFirsts) / sizeof(kFemaleFirsts[0]);
}

int16_t getFirstId(bool male, int index) {
    const int count = getFirstCount(male);
    if (index < 0 || index >= count) return -1;
    return male ? kMaleFirsts[index] : kFemaleFirsts[index];
}

int getPrefixCount() {
    return sizeof(kLastPrefixes) / sizeof(kLastPrefixes[0]);
}

int16_t getPrefixId(int index) {
    const int count = getPrefixCount();
    if (index < 0 || index >= count) return -1;
    return kLastPrefixes[index];
}

int getSuffixCount() {
    return sizeof(kLastSuffixes) / sizeof(kLastSuffixes[0]);
}

int16_t getSuffixId(int index) {
    const int count = getSuffixCount();
    if (index < 0 || index >= count) return -1;
    return kLastSuffixes[index];
}

int findTitleIndex(bool male, int16_t id) {
    const int count = getTitleCount(male);
    for (int i = 0; i < count; i++) {
        if (getTitleId(male, i) == id) return i;
    }
    return -1;
}

int findFirstIndex(bool male, int16_t id) {
    const int count = getFirstCount(male);
    for (int i = 0; i < count; i++) {
        if (getFirstId(male, i) == id) return i;
    }
    return -1;
}

int findPrefixIndex(int16_t id) {
    const int count = getPrefixCount();
    for (int i = 0; i < count; i++) {
        if (getPrefixId(i) == id) return i;
    }
    return -1;
}

int findSuffixIndex(int16_t id) {
    const int count = getSuffixCount();
    for (int i = 0; i < count; i++) {
        if (getSuffixId(i) == id) return i;
    }
    return -1;
}

void buildPatternName(int16_t p1, uint8_t f1,
                      int16_t p2, uint8_t f2,
                      int16_t p3, uint8_t f3,
                      int16_t p4, uint8_t f4,
                      char* out, size_t outSize) {
    if (!out || outSize == 0) return;
    out[0] = '\\0';

    char parts[4][64] = {};
    const int16_t p[4] = {p1, p2, p3, p4};
    const uint8_t f[4] = {f1, f2, f3, f4};

    for (int i = 0; i < 4; i++) {
        if (p[i] >= 0 && p[i] < kTotalNameMasterEntries) {
            const char* src = kNameMaster[p[i]].text;
            if (f[i]) {
                parts[i][0] = static_cast<char>(toupper(static_cast<unsigned char>(src[0])));
                strncpy(parts[i] + 1, src + 1, sizeof(parts[i]) - 2);
                parts[i][sizeof(parts[i]) - 1] = '\\0';
            } else {
                size_t j = 0;
                for (; src[j] && j < sizeof(parts[i]) - 1; j++) {
                    parts[i][j] = static_cast<char>(tolower(static_cast<unsigned char>(src[j])));
                }
                parts[i][j] = '\\0';
            }
        }
    }

    // Upstream: parts[2] += parts.pop(3) (suffix concatenated directly to prefix)
    if (parts[3][0] != '\\0') {
        const size_t curLen = strlen(parts[2]);
        if (curLen < sizeof(parts[2]) - 1) {
            strncat(parts[2], parts[3], sizeof(parts[2]) - curLen - 1);
        }
        parts[3][0] = '\\0';
    }

    // Join non-empty parts with space:
    for (int i = 0; i < 3; i++) {
        if (parts[i][0] != '\\0') {
            if (out[0] != '\\0') {
                const size_t len = strlen(out);
                if (len + 1 < outSize) {
                    strncat(out, " ", outSize - len - 1);
                }
            }
            const size_t len = strlen(out);
            if (len < outSize - 1) {
                strncat(out, parts[i], outSize - len - 1);
            }
        }
    }
}

void randomPattern(bool male, int16_t outP[4], uint8_t outF[4]) {
    // Upstream NameGenerator.py randomNameMoreinfo:
    // uberFlag in ['title-first', 'title-last', 'first', 'last', 'first-last', 'title-first-last']
    const int uberFlag = rand() % 6;
    bool titleFlag = false;
    bool firstFlag = false;
    bool lastFlag = false;
    switch (uberFlag) {
    case 0: titleFlag = true;  firstFlag = true;  break; // title-first
    case 1: titleFlag = true;  lastFlag = true;   break; // title-last
    case 2: firstFlag = true;                     break; // first
    case 3: lastFlag = true;                      break; // last
    case 4: firstFlag = true;  lastFlag = true;   break; // first-last
    case 5: titleFlag = true;  firstFlag = true;  lastFlag = true; break; // title-first-last
    }

    outP[0] = -1; outF[0] = 1;
    outP[1] = -1; outF[1] = 1;
    outP[2] = -1; outF[2] = 1;
    outP[3] = -1; outF[3] = 0;

    if (titleFlag) {
        const int count = getTitleCount(male);
        if (count > 0) {
            outP[0] = getTitleId(male, rand() % count);
            outF[0] = 1;
        }
    }
    if (firstFlag) {
        const int count = getFirstCount(male);
        if (count > 0) {
            outP[1] = getFirstId(male, rand() % count);
            const char* s = getNameString(outP[1]);
            outF[1] = (strcmp(s, "von") == 0) ? 0 : 1;
        }
    }
    if (lastFlag) {
        const int pCount = getPrefixCount();
        const int sCount = getSuffixCount();
        if (pCount > 0 && sCount > 0) {
            outP[2] = getPrefixId(rand() % pCount);
            outP[3] = getSuffixId(rand() % sCount);
            outF[2] = 1;
            outF[3] = isCapPrefix(outP[2]) ? 1 : 0;
        }
    }
}

} // namespace tt::game
""")

    with open("source/game/name_tables.cpp", "w", encoding="utf-8") as f:
        f.write("\n".join(cpp_lines) + "\n")

    print(f"Generated source/game/name_tables.h and source/game/name_tables.cpp from {txt_path} ({total} entries)")

if __name__ == "__main__":
    main()
