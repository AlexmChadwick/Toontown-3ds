#!/usr/bin/env python3
"""DistributedLaserField.makeGridSymbols (ref/open-toontown) -> source/world/laser_symbols.h.

The laser field draws gridSymbols[fieldData[x][y]] as a closed outline in each tile (unit tile
coordinates) in the symbol's colour, plus symbolSelect under the Toon. Plain Python, no panda3d:
    python3 -I tools/gen_laser_symbols.py
"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'ref/open-toontown/toontown/coghq/DistributedLaserField.py'
OUT = ROOT / 'source/world/laser_symbols.h'


def symbols(src):
    tree = ast.parse(src.read_text())
    fn = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == 'makeGridSymbols')
    code = compile(ast.Module(body=[fn], type_ignores=[]), str(src), 'exec')
    env = {}
    exec(code, env)

    class Self:
        def sendFail(self):
            pass
    s = Self()
    env['makeGridSymbols'](s)
    return s.gridSymbols, s.symbolSelect


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    grid, select = symbols(src)
    pts, table = [], []
    for sym in grid:
        table.append((len(pts), len(sym[2]), sym[1], sym[0] is not None and sym[0] != 0))
        pts.extend(sym[2])
    sel_first = len(pts)
    pts.extend(select[1])
    f = lambda v: f'{float(v)!r}f'
    out = ['// Generated by tools/gen_laser_symbols.py from DistributedLaserField.makeGridSymbols.',
           '#pragma once', '', '#include <cstdint>', '', 'namespace tt::world::laser {', '',
           'struct Symbol {', '    uint16_t first, count; // into kPoints (a closed line strip)',
           '    float color[3];', '    bool hazard; // calls sendFail when stepped on', '};', '',
           f'constexpr int kNumSymbols = {len(grid)};',
           'constexpr float kPoints[][2] = {']
    out += [f'    {{{f(x)}, {f(y)}}},' for x, y, *_ in pts]
    out += ['};', 'constexpr Symbol kSymbols[kNumSymbols] = {']
    for first, count, col, hazard in table:
        out.append(f'    {{{first}, {count}, {{{f(col[0])}, {f(col[1])}, {f(col[2])}}}, {str(hazard).lower()}}},')
    out += ['};', '// symbolSelect: the outline under the Toon.',
            f'constexpr Symbol kSelect = {{{sel_first}, {len(select[1])}, {{{f(select[0][0])}, {f(select[0][1])}, '
            f'{f(select[0][2])}}}, false}};', '', '} // namespace tt::world::laser', '']
    OUT.write_text('\n'.join(out))
    print(f'{OUT}: {len(grid)} symbols, {len(pts)} points')


if __name__ == '__main__':
    main()
